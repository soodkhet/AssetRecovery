// R15b.12 U109 หน้าจอรอบจ่าย (รายการ + รายละเอียด) + รายงาน F4 แยก "ภาษีที่บริษัทออกให้"
import { openAs, shot, BASE, settle, sleep, log, R, get } from './_h.mjs'
const flat = s => s.replace(/\s*\n+\s*/g, ' | ')
const { browser, page, serverErrors, consoleErrors } = await openAs('uat.finance')
await page.goto(`${BASE}/finance?tab=payout`); await settle(page); await sleep(1500)
const row = page.locator('tbody tr').filter({ hasText: 'UAT R15b IN on' })
log('list row:', flat(await row.innerText()))
log('list header:', flat(await page.locator('thead').first().innerText()))
await shot(page, R, 'b-12-payout-list', { fullPage: true })
await row.getByRole('button', { name: 'ดูรายการ' }).or(row.getByText('ดูรายการ')).first().click(); await sleep(1800)
const d = page.getByRole('dialog').last()
log('detail:', flat(await d.innerText()).slice(0, 3000))
await shot(page, R, 'b-12-payout-detail', { fullPage: true })
await page.keyboard.press('Escape'); await sleep(400)
await page.goto(`${BASE}/reports/compensation`); await settle(page); await sleep(2500)
log('F4 page:', flat(await page.locator('main').innerText()).slice(0, 2500))
await shot(page, R, 'b-12-f4-report', { fullPage: true })
log('F4 API:', await get(page, '/api/reports/finance/compensation?groupBy=employee', 2500))
log('5xx', serverErrors, consoleErrors.slice(0, 3))
await browser.close()
