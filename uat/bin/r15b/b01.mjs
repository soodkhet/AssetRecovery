// R15b.01 in1 (มือถือ) เบิกค่าที่พัก วันที่ พ.ย. + ไม่มีใบเสร็จ → ใบรับรองแทนใบเสร็จ
import { openAs, shot, BASE, settle, sleep, toasts, trackMutations, log, R, q, mainText } from './_h.mjs'
const { browser, page, consoleErrors, serverErrors } = await openAs('uat.agent.in1', { mobile: true })
const mut = trackMutations(page)
await page.goto(`${BASE}/field/expenses`); await settle(page); await sleep(1200)
await page.getByRole('button', { name: 'เบิกแยก', exact: true }).click(); await sleep(900)
await page.getByRole('button', { name: /เบิกที่พัก/ }).click(); await sleep(900)
const dlg = page.getByRole('dialog').filter({ hasText: 'เบิกค่าที่พัก' }).last(); await dlg.waitFor()
await dlg.locator('input[type=date]').first().fill(process.env.D ?? '2026-11-03')
await dlg.getByText('ไม่มีใบเสร็จ', { exact: true }).click(); await sleep(600)
log('modal after tick:', (await dlg.innerText()).replace(/\s+/g, ' ').slice(0, 900))
await dlg.getByLabel('วันที่จ่าย รายการที่ 1').fill(process.env.D ?? '2026-11-03')
await dlg.getByLabel('รายละเอียดรายจ่าย รายการที่ 1').fill('ค่าที่พักโรงแรมเล็ก ไม่ออกใบเสร็จ อ.บางพลี')
await dlg.getByLabel('จำนวนเงิน (บาท) รายการที่ 1').fill(process.env.AMT ?? '500')
await dlg.getByLabel('หมายเหตุ รายการที่ 1').fill('ผู้รับเงิน: นางสมใจ เจ้าของที่พัก')
await sleep(500)
await shot(page, R, 'b-01-hotel-no-receipt-form', { fullPage: true })
log('modal before submit:', (await dlg.innerText()).replace(/\s+/g, ' ').slice(0, 900))
mut.res.length = 0
await dlg.getByRole('button', { name: 'ส่งคำขอเบิก' }).click(); await sleep(3000)
log('toasts', await toasts(page, 1500), 'res', mut.res)
await settle(page); await sleep(800)
await shot(page, R, 'b-01-hotel-after-submit', { fullPage: true })
log(await mainText(page, 1800))
log(q(`select receipt_number,status,issue_date,total_satang,expense_id from substitute_receipts order by created_at desc limit 3`))
log('5xx', serverErrors, consoleErrors.slice(0, 3))
await browser.close()
