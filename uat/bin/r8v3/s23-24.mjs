log('23 main after', await mainText(p, 1800))
await shot(p, R, '23c-exec-adjustment-approved', { fullPage: true })
let r = await api(p, 'PATCH', `/api/adjustments/${A1}/approve`, { note: 'ซ้ำ probe' }); log('23 approve ซ้ำ', r); guard2xx('23dup', r)
