log('23 sql adj', q(`select status, approved_by=(select id from users where username='uat.exec') by_exec, approved_at from adjustments where id='${A1}'`))
log('23 sql audit', q(`select action, actor_role, left(reason,90) reason, after_data->>'status' st, after_data->>'signed_satang' signed, after_data->>'locked_period_adjustment' sep from audit_logs where target_type='adjustments' and target_id='${A1}' order by created_at`))
