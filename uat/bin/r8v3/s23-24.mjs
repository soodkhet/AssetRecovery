import { openAs, shot, R, ID, log, q, q1, settle, sleep, waitToast, mainText, dlgText, BASE, api, guard2xx, auditSince } from './_h.mjs'
log('=== R8.23-24', new Date().toISOString())
const T = q1('select now()'); log('T', T)
const A1 = q1('select id from adjustments order by created_at limit 1')
const e = await openAs('uat.exec'); const p = e.page
await p.goto(`${BASE}/finance?tab=adjustment`); await settle(p); await sleep(1200)
log('23 exec main', await mainText(p, 1600))
await shot(p, R, '23a-exec-adjustment-pending', { fullPage: true })
const row = p.locator('tbody tr').filter({ hasText: 'UAT-CO1-001' }).first()
await row.getByRole('button', { name: /อนุมัติ/ }).first().click(); await sleep(800)
const d = p.locator('[role="dialog"]').last()
await d.locator('textarea').fill('อนุมัติส่วนลดตามหนังสือตกลงกับ CO1 — ให้สำนักงานบัญชีออกใบลดหนี้ในเดือนปัจจุบัน')
log('23 dlg', await dlgText(p, 1500))
await shot(p, R, '23b-exec-approve-modal')
const resps = []; p.on('response', x => { if (x.url().includes(`/api/adjustments/${A1}/approve`)) resps.push(x) })
await d.getByRole('button', { name: /ยืนยันอนุมัติ/ }).dblclick(); await sleep(3000)
for (const x of resps) log('23 approve resp', x.status(), (await x.text()).slice(0, 600))
