// R15c.07 U103 — in2 (มือถือ) เคลียร์เงินทดรอง ADV3 ฿2,000 ใช้จริง ฿300 ไม่มีใบเสร็จ → ใบรับรองแทนใบเสร็จ (ผูกเงินทดรอง)
import { openAs, shot, BASE, settle, sleep, toasts, trackMutations, log, R, q } from './_h.mjs'
const ADV = '1959af6d-be83-40dd-9f8f-16d537785bbd'
const T = new Date().toISOString()
const flat = s => s.replace(/\s+/g, ' ')
const { browser, page, serverErrors, consoleErrors } = await openAs('uat.agent.in2', { mobile: true })
log('== c07', T)
const mut = trackMutations(page)
await page.goto(`${BASE}/field/advances`); await settle(page); await sleep(1500)
log('advances page', flat(await page.locator('main').innerText()).slice(0, 900))
await shot(page, R, 'c-07-field-advances', { fullPage: true })
await page.getByRole('button', { name: 'เคลียร์ยอด' }).first().click(); await sleep(900)
const d = page.getByRole('dialog').last()
await d.getByLabel('ยอดที่ใช้จริง (บาท)').fill('300').catch(async () => { await d.locator('input[inputmode=decimal]').first().fill('300') })
await sleep(400)
await d.getByText('รับคืนแยก (เงินสด/โอน)').click()
await d.getByText('ไม่มีใบเสร็จ', { exact: false }).first().click(); await sleep(500)
await d.getByLabel('วันที่จ่าย รายการที่ 1').fill('2026-10-05')
await d.getByLabel('รายละเอียดรายจ่าย รายการที่ 1').fill('ค่าทางด่วน + ค่าที่จอดรถ ไม่มีใบเสร็จ (UAT R15c)')
await d.getByLabel('จำนวนเงิน (บาท) รายการที่ 1').fill('300')
await d.getByLabel('หมายเหตุ รายการที่ 1').fill('ด่านบางนา / ลานจอดตลาด')
log('modal', flat(await d.innerText()).slice(0, 1500))
await shot(page, R, 'c-07-settle-modal', { fullPage: true })
mut.res.length = 0
const btns = await d.getByRole('button').allInnerTexts(); log('buttons', btns)
await d.getByRole('button', { name: /บันทึก|ยืนยัน|เคลียร์/ }).last().click(); await sleep(3000)
log('toasts', await toasts(page, 1000), 'res', mut.res)
await settle(page); await sleep(800)
await shot(page, R, 'c-07-settled', { fullPage: true })
log('after', flat(await page.locator('main').innerText()).slice(0, 1200))
log(q(`select status,approved_satang,used_satang,return_satang,cleared_at,return_method from advances where id='${ADV}'`))
log(q(`select id,receipt_number,status,advance_id,total_satang,issue_date from substitute_receipts where advance_id='${ADV}'`))
log(q(`select action,target_type,reason from audit_logs where created_at>'${T}' and action<>'login' order by created_at`))
log('5xx', serverErrors, consoleErrors.slice(0, 3))
await browser.close()
