// R15c.01 รอบจ่าย "UAT R15b IN on" (ค่าตั้ง (2)/(3) ปิดอยู่) → สร้างไฟล์โอน → ดาวน์โหลด → ยืนยันจ่ายแล้ว
import { writeFileSync, readFileSync } from 'node:fs'
import { openAs, shot, log, settle, sleep, R, q, BASE, toasts, DL, get } from './_h.mjs'
const NAME = 'UAT R15b IN on', ID = '4b234a2e-5c73-4504-8cbe-fc5611166a77'
const BFF = 'add7ece2-24bc-4166-bbf5-2f6c4b1702d7', BACC = 'c30800c4-52c6-431a-a357-b073cf077b89'
const T = new Date().toISOString()
const flat = s => s.replace(/\s*\n+\s*/g, ' | ')
const { browser, page, serverErrors } = await openAs('uat.finance')
log('== c01', T, 'policy', await get(page, '/api/payees/wht-condition-policy'))
const resps = []
page.on('response', async r => { if (r.request().method() !== 'GET' && r.url().includes('/api/payout')) resps.push(`${r.status()} ${new URL(r.url()).pathname} ${(await r.text().catch(() => '')).slice(0, 300)}`) })
await page.goto(`${BASE}/finance?tab=payout`); await settle(page); await sleep(1200)
const row = () => page.locator('tbody tr').filter({ hasText: NAME })
log('row before', flat(await row().innerText()))
await row().getByRole('button', { name: /สร้างไฟล์โอน/ }).click(); await sleep(1500)
const g = page.locator('[role="dialog"]').last()
await g.locator('select').first().selectOption(BFF); await g.locator('select').nth(1).selectOption(BACC)
await g.locator('textarea').first().fill('UAT R15c สร้างไฟล์โอนรอบ R15b IN on (เงื่อนไข 2/3)')
log('gen modal', flat(await g.innerText()).slice(0, 800))
await shot(page, R, 'c-01-genfile-modal')
const [resp] = await Promise.all([page.waitForResponse(x => x.url().includes('/generate-payment-file'), { timeout: 20000 }), g.getByRole('button', { name: /^สร้างไฟล์โอน$/ }).click()])
log('gen', resp.status(), (await resp.text()).slice(0, 400)); log('toasts', await toasts(page, 2500))
await shot(page, R, 'c-01-file-generated')
const dlg2 = page.locator('[role="dialog"]').last(); if (await dlg2.count()) await dlg2.getByRole('button', { name: 'ปิด' }).click().catch(() => {})
for (const [p, fn] of [['payment-file', 'c01-payment.csv'], ['voucher-pdf', 'c01-voucher-before.pdf'], ['summary-pdf', 'c01-summary.pdf']]) {
  const r = await page.request.get(`${BASE}/api/payout-batches/${ID}/${p}`, { failOnStatusCode: false })
  writeFileSync(`${DL}/${fn}`, await r.body()); log('download', p, r.status(), r.headers()['content-type'], r.headers()['content-disposition'])
}
log('csv:\n' + readFileSync(`${DL}/c01-payment.csv`, 'utf8').slice(0, 800))
await page.reload(); await settle(page); await sleep(1000)
log('row after gen', flat(await row().innerText()))
await row().getByRole('button', { name: /ยืนยันจ่ายแล้ว/ }).click(); await sleep(700)
const c = page.locator('[role="dialog"]').last()
log('complete modal', flat(await c.innerText()).slice(0, 800))
await c.locator('textarea').fill('ตรวจสลิปโอนกสิกรไทยครบ ยอด 22,345.67 (UAT R15c)')
await shot(page, R, 'c-01-complete-modal')
await c.getByRole('button', { name: 'ยืนยันจ่ายแล้ว' }).click()
log('toasts', await toasts(page, 4000), resps.splice(0))
await settle(page); await sleep(800); await shot(page, R, 'c-01-completed', { fullPage: true })
log('row final', flat(await row().innerText()))
const r2 = await page.request.get(`${BASE}/api/payout-batches/${ID}/voucher-pdf`, { failOnStatusCode: false })
writeFileSync(`${DL}/c01-voucher-after.pdf`, await r2.body()); log('voucher after', r2.status(), r2.headers()['content-disposition'])
log('5xx', serverErrors)
await browser.close()
log(q(`select name,status,payment_file_url,payment_file_generated_at,idempotency_key from payout_batches where id='${ID}'`))
log(q(`select certificate_number,status,payee_name_title,payee_name,gross_satang,wht_satang,wht_condition,filing_form,income_type,payment_date from wht_certificates where created_at>'${T}'`))
log(q(`select * from wht_filing_summaries`))
log(q(`select count(*) from expense_records where created_at>'${T}'`))
log(q(`select a.action,a.target_type,a.reason from audit_logs a where a.created_at>'${T}' and a.action<>'login' order by a.created_at`))
