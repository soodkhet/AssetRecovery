import { openAs, shot, log, settle, sleep, R, BASE, mainText, toasts, q, post, trackMutations } from './_h.mjs'
const PID = '9df4509f-c201-4dcf-8939-e02e08df748f'
const T = new Date().toISOString()
const flat = s => s.replace(/\s*\n+\s*/g, ' | ')
const { browser, page, serverErrors } = await openAs('uat.finance')
const m = trackMutations(page)
await page.goto(`${BASE}/finance?tab=payee`); await settle(page); await sleep(1200)
const row = () => page.locator('tbody tr').filter({ hasText: 'อนันต์' })
await row().getByRole('button', { name: 'แก้ไข' }).click(); await sleep(1000)
const d = page.locator('[role=dialog]').last()
await d.locator('#payee-name-title').selectOption({ label: 'นาย' })
await d.locator('[id$=-detail]').fill('99/9 หมู่ 1')
await d.locator('[id$=-province]').selectOption({ label: 'กรุงเทพมหานคร' }); await sleep(300)
await d.locator('[id$=-district]').fill('ห้วยขวาง')
await d.locator('[id$=-subdistrict]').fill('บางกะปิ')
await d.locator('[id$=-postal]').fill('10310'); await sleep(300)
log('after fill', await d.locator('[id$=-province]').inputValue(), await d.locator('[id$=-district]').inputValue(), await d.locator('[id$=-subdistrict]').inputValue())
await d.locator('#payee-reason').fill('UAT R14 กรอกคำนำหน้าและที่อยู่สำหรับ 50 ทวิ')
log('buttons', await d.getByRole('button').allInnerTexts())
await shot(page, R, '23-payee-form-filled', { fullPage: true })
await d.getByRole('button', { name: /^บันทึก/ }).last().click()
log('save toasts', await toasts(page, 3000), m.res.splice(0))
await settle(page); await sleep(800)
log('row after', flat(await row().innerText()))
await shot(page, R, '23-payee-pending', { fullPage: true })
log('db', q(`select name_title,address_detail,address_subdistrict,address_district,address_province,address_postal_code,is_verified,verified_by,verified_at from payee_profiles where id='${PID}'`))
// probe: สร้างรอบจ่าย inhouse ผ่านหน้าจอ ขณะ in1 รอยืนยัน
await page.goto(`${BASE}/finance?tab=payout`); await settle(page); await sleep(1000)
await page.getByRole('button', { name: '+ สร้างรอบจ่าย' }).click(); await sleep(800)
const c = page.locator('[role=dialog]').last()
await c.locator('select').first().selectOption('inhouse'); await sleep(800)
log('create modal (unverified)', flat(await c.innerText()).slice(0, 900))
await c.locator('input[type=date]').fill('2026-10-06')
await c.locator('input:not([type=date])').last().fill('UAT IN-R14 probe unverified')
await c.getByRole('button', { name: 'สร้างรอบจ่าย' }).click()
log('probe toasts', await toasts(page, 3000), m.res.splice(0))
await shot(page, R, '23-probe-payout-unverified', { fullPage: true })
await page.keyboard.press('Escape').catch(() => {})
log('batches', q(`select name,status from payout_batches where created_at>'${T}'`))
// ยืนยันใหม่
await page.goto(`${BASE}/finance?tab=payee`); await settle(page); await sleep(1200)
log('row buttons', await row().getByRole('button').allInnerTexts())
await row().getByRole('button', { name: /ยืนยัน/ }).first().click(); await sleep(900)
const v = page.locator('[role=dialog]').last()
log('verify modal', flat(await v.innerText()).slice(0, 900))
const ta = v.locator('textarea'); if (await ta.count()) await ta.first().fill('UAT R14 ตรวจที่อยู่ตามบัตรประชาชนแล้ว')
await shot(page, R, '23-verify-modal')
await v.getByRole('button', { name: /ยืนยัน/ }).last().click()
log('verify toasts', await toasts(page, 3000), m.res.splice(0))
await settle(page); await sleep(800)
log('row final', flat(await row().innerText()))
await shot(page, R, '23-payee-verified', { fullPage: true })
log('5xx', serverErrors)
await browser.close()
log('db', q(`select name_title,address_detail,is_verified,verified_by,verified_at from payee_profiles where id='${PID}'`))
log(q(`select a.action,a.reason,a.before->>'is_verified' bv,a.after->>'is_verified' av,a.after->>'name_title' t,a.after->>'address_detail' ad from audit_logs a where a.target_id='${PID}' and a.created_at>'${T}' order by a.created_at`))
