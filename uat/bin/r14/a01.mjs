// R14.01 ธุรการส่งเคสใหม่ UAT-CO2-R14 (กรอกมือ + แนบ 3 ไฟล์ → ร่าง → ส่งตรวจสอบ)
import { openAs, shot, log, settle, sleep, R, q, BASE, toasts, trackMutations, mainText, F } from './_h.mjs'
const REF = 'UAT-CO2-R14'
const { browser, page, serverErrors, consoleErrors } = await openAs('uat.admin')
const m = trackMutations(page)
await page.goto(`${BASE}/cases/submit`); await settle(page); await sleep(800)
await page.getByRole('button', { name: '+ รับเคส (กรอกมือ)' }).click()
const dlg = page.getByRole('dialog').last(); await dlg.waitFor(); await sleep(800)
await dlg.locator('#case-company').selectOption({ label: 'บริษัท ยูเอที แคปปิตอล จำกัด' })
await dlg.locator('#case-ref').fill(REF)
await dlg.locator('#debtor-name').fill('ทดสอบ อาร์สิบสี่')
await dlg.locator('#debtor-nationality').selectOption({ label: 'ไทย' }).catch(() => {})
await dlg.locator('#debtor-national-id').fill('3103700000140')
await dlg.locator('#debtor-mobile').fill('0891000014')
const detail = dlg.locator('[id$="-detail"]:is(input,textarea)')
const postal = dlg.locator('input[id$="-postal"]')
const prov = dlg.locator('select[id$="-province"]')
await prov.nth(0).selectOption({ label: 'กรุงเทพมหานคร' })
await detail.nth(0).fill('14 ถ.สุขุมวิท แขวงคลองเตย')
await postal.nth(2).fill('10110'); await sleep(1500)
if ((await prov.nth(2).inputValue()) !== 'กรุงเทพมหานคร') await prov.nth(2).selectOption({ label: 'กรุงเทพมหานคร' })
await detail.nth(2).fill('14 ถ.สุขุมวิท')
await dlg.locator('#asset-type').selectOption({ label: 'สมาร์ทโฟน' })
await dlg.locator('#asset-model').fill('Samsung Galaxy A16')
await dlg.locator('#asset-imei').fill('356789100000141')
await dlg.locator('#asset-debt').fill('10000.00')
const fi = dlg.locator('input[type=file]')
await fi.nth(0).setInputFiles(F('C7-contract.pdf'))
await fi.nth(1).setInputFiles(F('C7-idcard.png'))
await fi.nth(3).setInputFiles(F('C7-product.png'))
await sleep(800)
await shot(page, R, '01-case-form', { fullPage: true })
await dlg.getByRole('button', { name: 'บันทึกเคสร่าง' }).click()
log('save toasts', await toasts(page, 6500), m.res.splice(0))
if (await dlg.isVisible().catch(() => false)) { log('!! dialog still open', (await dlg.innerText()).replace(/\s+/g, ' ').slice(0, 600)); await shot(page, R, '01-case-form-error', { fullPage: true }); await browser.close(); process.exit(1) }
await settle(page)
const resP = page.waitForResponse(x => x.url().includes('/status') && x.request().method() === 'PATCH')
await page.locator('tr', { hasText: REF }).first().getByRole('button', { name: 'ส่งตรวจสอบเคส' }).click()
const res = await resP; log('PATCH submit', res.status())
log('toasts', await toasts(page, 2500))
await settle(page)
log('row', (await page.locator('tr', { hasText: REF }).first().innerText()).replace(/\s+/g, ' '))
await shot(page, R, '01-case-submitted')
log(q(`select c.status,c.imei,c.debt_amount_satang debt,c.projected_revenue_satang proj,st.name sugg,c.addr_province from cases c left join teams st on st.id=c.suggested_team_id where case_ref='${REF}'`))
log(q(`select d.doc_type,d.storage_path from case_documents d join cases c on c.id=d.case_id where c.case_ref='${REF}' and d.deleted_at is null`))
log(q(`select action,target_type,created_at from audit_logs where target_id=(select id from cases where case_ref='${REF}') order by created_at`))
log('5xx', serverErrors, 'console', consoleErrors.slice(0, 3))
await browser.close()
