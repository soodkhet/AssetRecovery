// R14.30 ปฏิทินวันหยุด: เพิ่ม 16/11/2569 → กำหนดยื่นเลื่อน 17/11 → ลบคืน → 16/11
import { openAs, shot, log, settle, sleep, R, BASE, toasts, q, mainText, trackMutations } from './_h.mjs'
import { fields } from '../r1/_h.mjs'
const T = new Date().toISOString()
const flat = s => s.replace(/\s*\n+\s*/g, ' | ')
const due = () => q(`select filing_due_date from wht_filing_summaries where period_label='ตุลาคม 2569'`).split('\n')[2]?.trim()
log('due before', due())
const { browser, page, serverErrors } = await openAs('uat.account')
const m = trackMutations(page)
const whtBanner = async tag => {
  await page.goto(`${BASE}/accounting?tab=wht`); await settle(page); await sleep(1500)
  const t = await mainText(page, 900); log(tag, t.slice(t.indexOf('เหลือ'), t.indexOf('เหลือ') + 260))
  await shot(page, R, `30-${tag}`)
}
await page.goto(`${BASE}/settings/finance?tab=holidays`); await settle(page); await sleep(1200)
await page.getByRole('button', { name: '+ เพิ่มวันหยุด' }).click(); await sleep(800)
const d = page.locator('[role=dialog]').last()
log('add modal', flat(await d.innerText()).slice(0, 600)); log('fields\n  ' + await fields(d))
await d.locator('input[type=date]').fill('2026-11-16')
await d.locator('input[type=text], input:not([type])').first().fill('UAT R14 วันหยุดทดสอบ')
await d.locator('textarea').first().fill('ทดสอบเลื่อนกำหนดยื่น')
await shot(page, R, '30-holiday-add-form')
await d.getByRole('button', { name: /บันทึก|เพิ่ม/ }).last().click()
log('add toasts', await toasts(page, 3000), m.res.splice(0))
await settle(page); await sleep(1000)
// ปีที่แสดงอาจเป็น 2569 อยู่แล้ว
log('holidays after add', (await mainText(page, 1600)).split('วันที่\tวัน').pop()?.slice(0, 400))
await shot(page, R, '30-holiday-added', { fullPage: true })
log('due after add', due(), q(`select holiday_date,name,deleted_at is null active from public_holidays`).replace(/\s+/g, ' '))
await whtBanner('wht-after-add')
// ลบคืน
await page.goto(`${BASE}/settings/finance?tab=holidays`); await settle(page); await sleep(1200)
const row = page.locator('tbody tr').filter({ hasText: 'UAT R14' })
log('row', flat(await row.innerText()), await row.getByRole('button').allInnerTexts())
await row.getByRole('button', { name: /ลบ/ }).click(); await sleep(800)
const x = page.locator('[role=dialog]').last()
log('delete modal', flat(await x.innerText()).slice(0, 500))
const ta = x.locator('textarea'); if (await ta.count()) await ta.first().fill('UAT R14 ลบวันหยุดทดสอบคืน')
await shot(page, R, '30-holiday-delete-modal')
await x.getByRole('button', { name: /ลบ|ยืนยัน/ }).last().click()
log('delete toasts', await toasts(page, 3000), m.res.splice(0))
await settle(page); await sleep(800); await shot(page, R, '30-holiday-deleted', { fullPage: true })
log('due after delete', due(), q(`select holiday_date,name,deleted_at is null active from public_holidays`).replace(/\s+/g, ' '))
await whtBanner('wht-after-delete')
log('5xx', serverErrors)
await browser.close()
log(q(`select a.action,a.target_type,a.reason,left(coalesce(a.before_data::text,''),120) b,left(coalesce(a.after_data::text,''),160) af from audit_logs a where a.created_at>'${T}' and a.action<>'login' order by a.created_at`))
