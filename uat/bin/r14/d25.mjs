import { writeFileSync, readFileSync } from 'node:fs'
import { openAs, shot, log, settle, sleep, R, q, BASE, toasts, DL } from './_h.mjs'
const NAME = 'UAT IN-R14'
const BFF = 'add7ece2-24bc-4166-bbf5-2f6c4b1702d7', BACC = 'c30800c4-52c6-431a-a357-b073cf077b89'
const T = new Date().toISOString()
const flat = s => s.replace(/\s*\n+\s*/g, ' | ')
const { browser, page, serverErrors } = await openAs('uat.finance')
const resps = []
page.on('response', async r => { if (r.request().method() !== 'GET' && r.url().includes('/api/payout')) resps.push(`${r.status()} ${new URL(r.url()).pathname} ${(await r.text().catch(() => '')).slice(0, 250)}`) })
await page.goto(`${BASE}/finance?tab=payout`); await settle(page); await sleep(1000)
await page.getByRole('button', { name: '+ สร้างรอบจ่าย' }).click(); await sleep(600)
const d = page.locator('[role="dialog"]').last()
await d.locator('select').first().selectOption('inhouse')
await d.locator('input[type=date]').fill('2026-10-06')
await d.locator('input:not([type=date])').last().fill(NAME)
await d.getByRole('button', { name: 'สร้างรอบจ่าย' }).click()
log('create toasts', await toasts(page, 4000), resps.splice(0))
await page.reload(); await settle(page); await sleep(1000)
const row = () => page.locator('tbody tr').filter({ hasText: NAME })
log('row', flat(await row().innerText()))
await row().getByRole('button', { name: 'ดูรายการ' }).click(); await sleep(1500)
log('detail', flat(await page.locator('[role="dialog"]').last().innerText()).slice(0, 2000))
await shot(page, R, '25-payout-detail', { fullPage: true })
const ID = q(`select id from payout_batches where name='${NAME}'`).split('\n')[2].trim()
log('batch', q(`select name,status,gross_satang,wht_satang,net_satang,advance_offset_satang,(select count(*) from payout_batch_items i where i.payout_batch_id=b.id) items from payout_batches b where id='${ID}'`))
log(q(`select x.expense_type,x.gross_satang from expenses x join payout_batch_items i on i.id=x.payout_batch_item_id where i.payout_batch_id='${ID}' order by 1`))
await page.keyboard.press('Escape'); await page.reload(); await settle(page); await sleep(1000)
// สร้างไฟล์โอน
await row().getByRole('button', { name: /สร้างไฟล์โอน/ }).click(); await sleep(1500)
const g = page.locator('[role="dialog"]').last()
await g.locator('select').first().selectOption(BFF); await g.locator('select').nth(1).selectOption(BACC)
await g.locator('textarea').first().fill('UAT R14 สร้างไฟล์โอนรอบ IN-R14')
log('gen modal', flat(await g.innerText()).slice(0, 700))
const [resp] = await Promise.all([page.waitForResponse(x => x.url().includes('/generate-payment-file'), { timeout: 20000 }), g.getByRole('button', { name: /^สร้างไฟล์โอน$/ }).click()])
log('gen', resp.status(), (await resp.text()).slice(0, 300)); log('toasts', await toasts(page, 2500))
await shot(page, R, '25-file-generated')
const dlg2 = page.locator('[role="dialog"]').last(); if (await dlg2.count()) await dlg2.getByRole('button', { name: 'ปิด' }).click().catch(() => {})
for (const [p, fn] of [['payment-file', 'IN-R14-payment.csv'], ['voucher-pdf', 'IN-R14-voucher.pdf'], ['summary-pdf', 'IN-R14-summary.pdf']]) {
  const r = await page.request.get(`${BASE}/api/payout-batches/${ID}/${p}`, { failOnStatusCode: false })
  writeFileSync(`${DL}/${fn}`, await r.body()); log('download', p, r.status(), r.headers()['content-type'], r.headers()['content-disposition'])
}
log('csv:\n' + readFileSync(`${DL}/IN-R14-payment.csv`, 'utf8').slice(0, 600))
// ยืนยันโอน
await page.reload(); await settle(page); await sleep(1000)
await row().getByRole('button', { name: '✓ ยืนยันจ่ายแล้ว' }).click(); await sleep(700)
const c = page.locator('[role="dialog"]').last()
log('complete modal', flat(await c.innerText()).slice(0, 700))
await c.locator('textarea').fill('ตรวจสลิปโอนกสิกรไทยครบ ยอด 1,309.50 (UAT R14)')
await c.getByRole('button', { name: 'ยืนยันจ่ายแล้ว' }).click()
log('toasts', await toasts(page, 4000), resps.splice(0))
await settle(page); await sleep(800); await shot(page, R, '25-completed', { fullPage: true })
await page.goto(`${BASE}/finance?tab=wht`); await settle(page); await sleep(1200)
log('wht tab', flat(await page.locator('main').innerText()).slice(0, 1500))
await shot(page, R, '25-wht-tab', { fullPage: true })
log('5xx', serverErrors)
await browser.close()
log(q(`select name,status,payment_file_url,payment_file_generated_at is not null gen from payout_batches where id='${ID}'`))
log(q(`select * from wht_certificates where created_at>'${T}'`))
