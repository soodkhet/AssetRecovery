import { openAs, shot, BASE, log, q, SQL, post, sleep, collect, trackApi, rowText, mainText, C, U } from './_h.mjs'
const go = async (p) => { await p.goto(`${BASE}/cases/assign`); await p.waitForLoadState('networkidle'); await sleep(600) }
log('\n===== R3.13', new Date().toISOString())
const m = await openAs('uat.mgr.in'), s = await openAs('uat.sup.in')
const fire = () => Promise.all([m.page.request.post(`${BASE}/api/cases/${C.C3}/assign`, { data: { agentId: U.in2 } }), s.page.request.post(`${BASE}/api/cases/${C.C3}/assign`, { data: { agentId: U.in2 } })])
const [r1, r2] = await fire()
log('race1 mgr:', r1.status(), (await r1.text()).slice(0, 220)); log('race1 sup:', r2.status(), (await r2.text()).slice(0, 220))
log('active C3:', q(SQL.active(C.C3)))
const [r3, r4] = await fire()
log('race2 mgr:', r3.status(), (await r3.text()).slice(0, 160)); log('race2 sup:', r4.status(), (await r4.text()).slice(0, 160))
log(q(`select a.id,u.username agent,a.status,cb.username by_user,a.created_at from case_assignments a join users u on u.id=a.agent_id join users cb on cb.id=a.created_by where a.case_id='${C.C3}'`))
log(q(`select count(*) audit_c3 from audit_logs where target_type='case_assignments' and target_id in (select id from case_assignments where case_id='${C.C3}')`))

log('\n===== R3.14', new Date().toISOString())
const mApi = trackApi(m.page)
await go(m.page)
await m.page.locator('tr', { hasText: 'UAT-CO1-001' }).first().getByRole('button', { name: 'มอบหมาย', exact: true }).click()
let d = m.page.getByRole('dialog'); await d.waitFor(); await sleep(1200)
const cardTxt = async (dl, name) => (await dl.locator('div', { hasText: name }).filter({ hasText: 'เคสในมือ' }).last().innerText().catch(() => '')).replace(/\s+/g, ' ').slice(0, 200)
log('card อนันต์:', await cardTxt(d, 'อนันต์ ตามทรัพย์')); log('card บุญมี:', await cardTxt(d, 'บุญมี ภาคสนาม'))
await d.getByText('อนันต์ ตามทรัพย์').first().click(); await sleep(300)
await shot(m.page, 'R3', '14-assign-C1-modal')
await d.getByRole('button', { name: 'ยืนยันมอบหมาย' }).dblclick()
log('toasts:', await collect(m.page, 3500))
log('api:', mApi.splice(0))
await go(m.page)
log('row C1:', await rowText(m.page, 'UAT-CO1-001'))
log('active C1:', q(SQL.active(C.C1)))
await shot(m.page, 'R3', '14-list-after-C1')

log('\n===== R3.15', new Date().toISOString())
const sApi = trackApi(s.page)
await go(s.page)
await s.page.locator('tr', { hasText: 'UAT-CO1-002' }).first().getByRole('button', { name: 'มอบหมาย', exact: true }).click()
d = s.page.getByRole('dialog'); await d.waitFor(); await sleep(1200)
log('card อนันต์:', await cardTxt(d, 'อนันต์ ตามทรัพย์'))
await d.getByText('อนันต์ ตามทรัพย์').first().click(); await sleep(300)
await shot(s.page, 'R3', '15-sup-assign-C2-modal')
await d.getByRole('button', { name: 'ยืนยันมอบหมาย' }).click()
log('toasts:', await collect(s.page, 3000)); log('api:', sApi)
await go(s.page)
log('row C2:', await rowText(s.page, 'UAT-CO1-002'))
log('KPI:', await mainText(s.page, 260))
await shot(s.page, 'R3', '15-sup-list-after-C2')
log(q(SQL.asg)); log(q(SQL.audit)); log(q(SQL.noti))
log('console m:', m.consoleErrors, m.serverErrors, 's:', s.consoleErrors, s.serverErrors)
for (const x of [m, s]) await x.browser.close()
