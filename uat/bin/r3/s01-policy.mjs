// R3.01 admin ตั้ง timeout = 1 ชม.
import { openAs, shot, BASE, log, q, SQL, collect, trackApi, mainText, sleep } from './_h.mjs'
log('\n===== R3.01', new Date().toISOString())
const { browser, page, consoleErrors, serverErrors } = await openAs('admin')
const api = trackApi(page)
await page.goto(`${BASE}/settings/finance?tab=assignment`); await page.waitForLoadState('networkidle')
const inp = page.locator('#assignment-reassign-timeout')
log('value:', await inp.inputValue())
const boxes = page.locator('main input[type="checkbox"]')
const states = []; for (let i = 0; i < await boxes.count(); i++) states.push(await boxes.nth(i).isChecked())
log('checkboxes:', states)
log('notice "ยังไม่เคยตั้งค่า":', await page.getByText('ยังไม่เคยตั้งค่า').count())
await shot(page, 'R3', '01-settings-default', { fullPage: true })
const saveBtn = page.getByRole('button', { name: 'บันทึกนโยบายการมอบหมายงาน' })
for (const v of ['0', '169']) {
  await inp.fill(v)
  const dis = await saveBtn.isDisabled()
  if (!dis) await saveBtn.click()
  const seen = await collect(page, 2500)
  const dlg = page.getByRole('dialog')
  const dlgOpen = await dlg.count()
  const errs = (await page.locator('main .text-red-600, main [role=alert]').allInnerTexts()).map(s => s.trim()).filter(Boolean)
  const valid = await inp.evaluate(e => e.validationMessage)
  log(`try ${v}: saveDisabled=${dis} dialog=${dlgOpen} toasts=`, seen, 'inline=', errs, 'html5=', valid)
  await shot(page, 'R3', `01-invalid-${v}`)
  if (dlgOpen) { log('  dialog text:', (await dlg.innerText()).replace(/\s+/g, ' ').slice(0, 300)); await page.keyboard.press('Escape'); await sleep(500) }
}
await inp.fill('1')
await saveBtn.click()
const dlg = page.getByRole('dialog')
await dlg.waitFor()
log('modal:', (await dlg.innerText()).replace(/\s+/g, ' ').slice(0, 500))
const reason = dlg.locator('#settings-reason')
const ok = dlg.getByRole('button', { name: 'บันทึก', exact: true })
await reason.fill('abcd')
log('reason abcd → บันทึก disabled:', await ok.isDisabled())
await shot(page, 'R3', '01-modal-short-reason')
await reason.fill('UAT R3 ลดเวลารอความยินยอมเหลือ 1 ชม. เพื่อทดสอบ timeout')
log('reason full → disabled:', await ok.isDisabled())
await ok.click()
log('toasts:', await collect(page, 3000))
await page.waitForLoadState('networkidle')
log('notice after:', await page.getByText('ยังไม่เคยตั้งค่า').count(), 'value:', await inp.inputValue())
await shot(page, 'R3', '01-settings-saved', { fullPage: true })
log('api:', api); log('console:', consoleErrors, 'server:', serverErrors)
log(q(SQL.pol)); log(q(SQL.audit))
await browser.close()
