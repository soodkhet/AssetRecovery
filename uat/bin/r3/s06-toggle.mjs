async function setInhouse(on, reason, tag) {
  await ad.page.goto(`${BASE}/settings/finance?tab=assignment`); await ad.page.waitForLoadState('networkidle'); await sleep(600)
  const cb = ad.page.getByLabel('หัวหน้าทีมกลุ่ม Inhouse มอบหมาย/เปลี่ยนผู้รับผิดชอบได้')
  if ((await cb.isChecked()) !== on) await cb.click()
  await ad.page.getByRole('button', { name: 'บันทึกนโยบายการมอบหมายงาน' }).click()
  const d = ad.page.getByRole('dialog'); await d.waitFor()
  log('modal:', (await d.innerText()).replace(/\s+/g, ' ').slice(0, 300))
  await d.locator('#settings-reason').fill(reason)
  await shot(ad.page, 'R3', `${tag}-settings-modal`)
  await d.getByRole('button', { name: 'บันทึก', exact: true }).click()
  log('toasts:', await collect(ad.page, 2500))
  log(q(SQL.pol))
}
