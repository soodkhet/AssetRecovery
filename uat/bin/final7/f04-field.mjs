// Flow 4 — in1 มือถือ 375×812: รับงาน → จัดวัน (วันนี้) → เริ่มงาน → เช็คอิน → ปิดงานสำเร็จ (รูป/วิดีโอ/รูปสินค้า → Storage)
import { openAs, shot, log, q } from './_h.mjs'
import { collect, trackApi } from '../r2/_h.mjs'
import { card, pick } from '../r4v3/_h.mjs'
const REF = 'FINAL7-001', NAME = 'นายทดสอบ ด่านเจ็ด'
const s = await openAs('uat.agent.in1', { mobile: true }); const { page, context } = s
await page.setViewportSize({ width: 375, height: 812 })
const api = trackApi(page)
const overflow = async () => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
const go = async p => { await page.goto('http://localhost:3000' + p); await page.waitForLoadState('networkidle'); await page.waitForTimeout(800); log('f04', p, 'overflowX=', await overflow()) }
await go('/field/pending')
await shot(page, 'final/flow', 'f04-m-pending')
await card(page, NAME, 'รับงาน').getByRole('button', { name: 'รับงาน', exact: true }).click()
log('f04', 'accept', await collect(page, 3000), api.splice(0).map(x => x.slice(0, 120)))
await go('/field/accepted')
await card(page, NAME, 'จัดวันที่').getByRole('button', { name: 'จัดวันที่' }).click()
const cal = page.getByRole('dialog').last(); await cal.waitFor(); await page.waitForTimeout(500)
await shot(page, 'final/flow', 'f04-m-calendar')
await cal.locator('button:has(> span:text-is("7"))').first().click(); await page.waitForTimeout(400)
log('f04', 'cal confirm text', (await cal.innerText()).replace(/\s+/g, ' ').slice(0, 200))
await page.getByRole('button', { name: 'ยืนยันเลือกวันนี้' }).click()
log('f04', 'schedule', await collect(page, 3000), api.splice(0).map(x => x.slice(0, 120)))
await context.grantPermissions(['geolocation'], { origin: 'http://localhost:3000' })
await context.setGeolocation({ latitude: 13.8166, longitude: 100.5612, accuracy: 15 })
await go('/field/tracking')
await shot(page, 'final/flow', 'f04-m-tracking')
await card(page, NAME, 'เริ่มงาน').getByRole('button', { name: 'เริ่มงาน' }).click()
const dlg = page.getByRole('dialog').last(); await dlg.waitFor(); await page.waitForTimeout(1200)
await dlg.getByRole('button', { name: 'สำเร็จ', exact: true }).click(); await page.waitForTimeout(600)
// validation: ปิดงานโดยไม่มีอะไร
await dlg.getByRole('button', { name: 'ยืนยันปิดงาน' }).click(); await page.waitForTimeout(1000)
log('f04', 'empty close msgs', (await dlg.getByText(/^ยังขาด/).allInnerTexts().catch(() => [])).join(' | '), await collect(page, 1200))
await shot(page, 'final/flow', 'f04-m-close-missing', { fullPage: true })
await dlg.getByRole('button', { name: /แตะเพื่อเช็คอินตำแหน่งปัจจุบัน/ }).click()
log('f04', 'checkin', await collect(page, 3500))
await pick(page, dlg, 'รูปถ่าย', 'uat/fixtures/files/R4-C1-photo.jpg')
await pick(page, dlg, 'วิดีโอ', 'uat/fixtures/files/R4-C1-video.mp4')
await pick(page, dlg, 'รูปสินค้ายืนยัน', 'uat/fixtures/files/R4-C1-product.jpg')
await shot(page, 'final/flow', 'f04-m-close-form', { fullPage: true })
await dlg.getByRole('button', { name: 'ยืนยันปิดงาน' }).click()
log('f04', 'close', await collect(page, 5000), api.splice(0).filter(x => !x.includes('/storage/')).map(x => x.slice(0, 160)))
await go('/field/closed'); await shot(page, 'final/flow', 'f04-m-closed')
await go('/field/income'); await shot(page, 'final/flow', 'f04-m-income')
log('f04', q(`select c.status,a.status asg,(select count(*) from check_ins k where k.case_id=c.id) ci,(select string_agg(e.status||':'||cardinality(e.photos)||'/'||cardinality(e.videos)||'/'||cardinality(e.product_photos),',') from case_evidences e where e.case_id=c.id) ev,(select string_agg(x.expense_type||':'||x.gross_satang||':'||x.status,',') from expenses x where x.case_id=c.id) ex,(select string_agg(s.asset_status,',') from assets s where s.case_id=c.id) asset from cases c join case_assignments a on a.case_id=c.id where c.case_ref='${REF}'`))
log('f04', 'storage paths', q(`select e.photos||e.videos||e.product_photos from case_evidences e join cases c on c.id=e.case_id where c.case_ref='${REF}'`))
log('f04', 'console', s.consoleErrors, s.serverErrors); await s.browser.close()
