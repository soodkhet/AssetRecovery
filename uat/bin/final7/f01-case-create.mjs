// Flow 1 — ธุรการรับเคสใหม่ CO1 (Model Phone จากรายการ) + validation ภาษาไทย → บันทึกร่าง → ส่งตรวจสอบ
import { openAs, shot, log, q } from './_h.mjs'
import { collect, trackApi } from '../r2/_h.mjs'
const REF = 'FINAL7-001'
const s = await openAs('uat.admin'); const { page } = s
const api = trackApi(page)
await page.goto('http://localhost:3000/cases/submit'); await page.waitForLoadState('networkidle')
await page.getByRole('button', { name: '+ รับเคส (กรอกมือ)' }).click()
const dlg = page.getByRole('dialog'); await dlg.waitFor(); await page.waitForTimeout(800)
// V1: กดบันทึกทั้งฟอร์มว่าง
await dlg.getByRole('button', { name: 'บันทึกเคสร่าง' }).click(); await page.waitForTimeout(1200)
const errs = async () => [...new Set((await dlg.locator('.text-red-600, .text-rose-600, [role=alert], p[id$="-error"]').allInnerTexts()).map(x => x.trim()).filter(Boolean))]
log('f01', 'V1 empty submit errors:', (await errs()).slice(0, 12).join(' | '), 'api:', api.splice(0))
await shot(page, 'final/flow', 'f01-v1-empty', { fullPage: true })
await dlg.locator('#case-company').selectOption({ label: 'บจก. ยูเอที ลิสซิ่ง' })
await dlg.locator('#case-ref').fill(REF)
await dlg.locator('#debtor-name').fill('นายทดสอบ ด่านเจ็ด')
await dlg.locator('#debtor-nationality').selectOption({ label: 'ไทย' })
await dlg.locator('#debtor-national-id').fill('1100000000999')
await dlg.locator('#debtor-mobile').fill('0899990007')
const detail = dlg.locator('[id$="-detail"]'), prov = dlg.locator('select[id$="-province"]'), postal = dlg.locator('input[id$="-postal"]')
await prov.nth(0).selectOption({ label: 'กรุงเทพมหานคร' }); await detail.nth(0).fill('99 ถ.พหลโยธิน แขวงจตุจักร')
await postal.nth(2).fill('10900'); await page.waitForTimeout(1500)
if (!(await prov.nth(2).inputValue())) await prov.nth(2).selectOption({ label: 'กรุงเทพมหานคร' })
await detail.nth(2).fill('99 ถ.พหลโยธิน แขวงจตุจักร')
await dlg.locator('#asset-type').selectOption({ label: 'สมาร์ทโฟน' })
// Model Phone: พิมพ์แล้วดูรายการแนะนำ
await dlg.locator('#asset-model').click(); await dlg.locator('#asset-model').fill('Sam'); await page.waitForTimeout(1200)
const sugg = (await page.locator('[role=listbox] [role=option], [role=option]').allInnerTexts()).map(x => x.trim())
log('f01', 'model suggestions for "Sam":', sugg.join(' | '))
await shot(page, 'final/flow', 'f01-model-suggest')
if (sugg.length) await page.locator('[role=option]').first().click()
else await dlg.locator('#asset-model').fill('Samsung Galaxy A55 5G')
await page.waitForTimeout(500)
log('f01', 'model value:', await dlg.locator('#asset-model').inputValue())
// V2: IMEI ผิด + มูลหนี้ติดลบ
await dlg.locator('#asset-imei').fill('35900-ABC-0007')
await dlg.locator('#asset-debt').fill('-500')
await dlg.locator('input[type=file]').nth(0).setInputFiles('uat/fixtures/files/C1-contract.pdf')
await dlg.locator('input[type=file]').nth(1).setInputFiles('uat/fixtures/files/C1-idcard.png')
await dlg.getByRole('button', { name: 'บันทึกเคสร่าง' }).click(); await page.waitForTimeout(1500)
log('f01', 'V2 bad imei/neg debt errors:', (await errs()).join(' | '), 'api:', api.splice(0))
await shot(page, 'final/flow', 'f01-v2-imei-negdebt', { fullPage: true })
await dlg.locator('#asset-imei').fill('3590-0000-0007-001')
await dlg.locator('#asset-debt').fill('15,000.50')
await dlg.getByRole('button', { name: 'บันทึกเคสร่าง' }).click()
log('f01', 'save toasts:', await collect(page, 6000))
log('f01', 'api:', api.splice(0).map(x => x.slice(0, 160)))
await page.waitForLoadState('networkidle')
log('f01', q(`select case_ref,status,imei,debt_amount_satang,asset_model,device_catalog_model_id is not null catalog from cases where case_ref='${REF}'`))
const row = page.locator('tr', { hasText: REF }).first()
log('f01', 'row:', (await row.innerText().catch(() => 'NO ROW')).replace(/\s+/g, ' '))
await row.getByRole('button', { name: 'ส่งตรวจสอบเคส' }).click().catch(e => log('f01', 'no submit btn'))
await page.waitForTimeout(800)
const cd = page.getByRole('dialog'); if (await cd.isVisible().catch(() => false)) { log('f01', 'confirm dlg:', (await cd.innerText()).replace(/\s+/g, ' ').slice(0, 200)); await cd.getByRole('button', { name: /ยืนยัน|ส่ง/ }).last().click() }
log('f01', 'submit toasts:', await collect(page, 4000), api.splice(0).map(x => x.slice(0, 160)))
log('f01', q(`select case_ref,status from cases where case_ref='${REF}'`))
await shot(page, 'final/flow', 'f01-submitted')
log('f01', 'console', s.consoleErrors, '5xx', s.serverErrors)
await s.browser.close()
