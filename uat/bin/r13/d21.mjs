// R13.21 อนุมัติ ADV5 + probe U83 (เคลียร์ก่อนจ่าย ต้องถูกบล็อก)
import { openAs, shot, log, settle, sleep, R, q, BASE, toasts } from './_h.mjs'
const ADV5 = '02221e05-4e8d-4e57-aa54-5d8cd8b557dd'
const { browser, page } = await openAs('uat.finance')
await page.goto(`${BASE}/finance?tab=approval`); await settle(page); await sleep(900)
const row = page.locator('tbody tr').filter({ hasText: 'อนันต์ ตามทรัพย์' }).filter({ hasText: '500.00' }).filter({ has: page.getByRole('button', { name: 'อนุมัติ', exact: true }) })
log('adv5 rows', await row.count())
await row.first().getByRole('button', { name: 'อนุมัติ', exact: true }).click(); await sleep(700)
const dlg = page.locator('[role="dialog"]').last()
log('modal', (await dlg.innerText()).replace(/\s*\n+\s*/g, ' | ').slice(0, 500))
await shot(page, R, '21-adv5-approve-modal')
await dlg.getByRole('button', { name: 'อนุมัติและปล่อยเงิน' }).click()
log('approve toasts', await toasts(page, 3000))
log(q(`select status,requested_satang,approved_satang from advances where id='${ADV5}'`))
await page.goto(`${BASE}/finance?tab=advance`); await settle(page); await sleep(1000)
const r5 = page.locator('tbody tr').filter({ hasText: 'UAT R13 ค่าเดินทาง' })
log('adv tab row', (await r5.first().innerText().catch(() => '')).replace(/\s+/g, ' ').slice(0, 300))
const sb = r5.first().getByRole('button', { name: /เคลียร์ยอด/ })
log('settle btn count', await sb.count(), 'disabled', await sb.first().isDisabled().catch(() => 'n/a'), 'title', await sb.first().getAttribute('title').catch(() => null))
await sb.first().hover().catch(() => {}); await sleep(600)
await shot(page, R, '21-adv5-settle-disabled', { fullPage: true })
const before = q(`select status,updated_at from advances where id='${ADV5}'`)
const r = await page.request.patch(`${BASE}/api/advances/${ADV5}/settle`, { data: { usedSatang: 35000, returnMethod: 'separate' }, failOnStatusCode: false })
log('API settle', r.status(), (await r.text()).slice(0, 300))
log('unchanged', before === q(`select status,updated_at from advances where id='${ADV5}'`))
await browser.close()
