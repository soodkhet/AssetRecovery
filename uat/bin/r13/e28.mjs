// R13.28 เคลียร์ ADV5 ใช้จริง 350.00 + เลือกรับคืนแยก
import { openAs, shot, log, settle, sleep, R, q, BASE, toasts } from './_h.mjs'
const ADV5 = '02221e05-4e8d-4e57-aa54-5d8cd8b557dd'
const flat = s => s.replace(/\s*\n+\s*/g, ' | ')
const { browser, page } = await openAs('uat.finance')
await page.goto(`${BASE}/finance?tab=advances`); await settle(page); await sleep(1000)
const row = page.locator('tbody tr').filter({ hasText: 'ADV-02221E05' }).first()
const b = row.getByRole('button', { name: /เคลียร์ยอด/ })
log('btn disabled', await b.isDisabled())
await b.click(); await sleep(900)
const d = page.locator('[role="dialog"]').last()
log('modal', flat(await d.innerText()).slice(0, 900))
log('inputs', await d.locator('input,select,textarea').evaluateAll(es => es.map(e => `${e.tagName}:${e.type}:${e.name || e.id}:${e.getAttribute('inputmode') ?? ''}`)))
await d.locator('input[inputmode=decimal]').first().fill('350')
await sleep(400)
const sep = d.getByText(/รับคืนแยก/).first()
if (await sep.count()) await sep.click()
await sleep(400)
log('modal filled', flat(await d.innerText()).slice(0, 900))
await shot(page, R, '28-adv5-settle-modal')
await d.getByRole('button', { name: 'บันทึกการเคลียร์ยอด' }).click()
log('toasts', await toasts(page, 3500))
await settle(page); await sleep(800)
log('row after', (await page.locator('tbody tr').filter({ hasText: 'ADV-02221E05' }).first().innerText()).replace(/\s+/g, ' ').slice(0, 300))
await shot(page, R, '28-adv5-cleared', { fullPage: true })
await browser.close()
log(q(`select status,used_satang,return_satang,return_method from advances where id='${ADV5}'`))
