// R13.07 มอบหมาย UAT-CO1-901 ให้ in1 (ผู้จัดการทีม A)
import { openAs, shot, log, settle, sleep, R, q, BASE, toasts, trackMutations, mainText } from './_h.mjs'
const T = new Date().toISOString()
const { browser, page, serverErrors } = await openAs('uat.mgr.in')
const m = trackMutations(page)
await page.goto(`${BASE}/cases/assign`); await settle(page); await sleep(800)
const row = page.locator('tr', { hasText: 'UAT-CO1-901' }).first()
log('row before', (await row.innerText()).replace(/\s+/g, ' '))
await row.getByRole('button', { name: 'มอบหมาย', exact: true }).click()
const d = page.getByRole('dialog'); await d.waitFor(); await sleep(1200)
await d.getByText('อนันต์ ตามทรัพย์').first().click(); await sleep(300)
await shot(page, R, '07-assign-modal')
await d.getByRole('button', { name: 'ยืนยันมอบหมาย' }).click()
log('toasts', await toasts(page, 3000)); log('mut', m.res)
await page.goto(`${BASE}/cases/assign`); await settle(page); await sleep(800)
const r2 = page.locator('tr', { hasText: 'UAT-CO1-901' }).first()
log('row after', (await r2.innerText().catch(() => '(ไม่อยู่ในรายการรอมอบหมาย)')).replace(/\s+/g, ' '))
log('main', await mainText(page, 800))
await shot(page, R, '07-assign-after', { fullPage: true })
await browser.close()
log(q(`select u.username,a.status,a.created_at from case_assignments a join users u on u.id=a.agent_id where a.case_id='b976a24e-af0d-490c-a8be-e402f9b9ecd4'`))
log(q(`select u.username,n.event_code,n.title,n.body from notifications n join users u on u.id=n.user_id where n.created_at>'${T}'`))
log('5xx', serverErrors)
