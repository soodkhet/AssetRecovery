// R13.18 สร้างล็อต CO1(901) + probe ผสมบริษัท + ล็อต CO2(007) · แนบใบเซ็นรับ + ยืนยันทั้งสอง
import { openAs, shot, log, settle, sleep, R, q, BASE, toasts, F, post } from './_h.mjs'
const CO1 = 'e27e79bf-2344-4f52-8979-c58be09a9de6', A901 = '395ac144-775b-4df9-baea-6cbe6bf7f5de', A007 = '9b94aed8-799c-46ce-b56d-8a1e60307f72'
const T = new Date().toISOString()
const SCHED = new Date(Date.now() + 7 * 3600e3 - 10 * 60e3).toISOString().slice(0, 16)
const { browser, page, serverErrors } = await openAs('uat.admin')
const res = []
page.on('response', r => { const u = r.url(); if (r.request().method() !== 'GET' && u.includes('/api/')) res.push(`${r.status()} ${r.request().method()} ${u.replace(/^https?:\/\/[^/]+/, '')}`) })
async function makeLot(co, n) {
  await page.goto(`${BASE}/warehouse`); await settle(page)
  await page.getByRole('tab', { name: /^ในคลัง/ }).click(); await sleep(800)
  await page.getByText(co).last().click(); await sleep(900)
  await page.getByRole('checkbox', { name: 'เลือกทุกเครื่องที่พร้อมส่ง' }).check(); await sleep(400)
  await page.getByRole('button', { name: /นัดวันส่งมอบ \(1\)/ }).click(); await sleep(900)
  const dlg = page.locator('[role="dialog"]').last()
  await dlg.getByRole('button', { name: /ไฟแนนซ์มารับที่คลัง/ }).click(); await sleep(300)
  await dlg.locator('input[type=datetime-local]').fill(SCHED)
  await dlg.getByPlaceholder('เช่น คุณวิภา ฝ่ายติดตามทรัพย์').fill('คุณวิภา ฝ่ายติดตามทรัพย์ (UAT)')
  await dlg.getByPlaceholder('บันทึกเพิ่มเติม...').fill(`UAT R13 ล็อต ${n}`)
  await dlg.getByRole('button', { name: 'บันทึกการนัด' }).click()
  log('lot', n, await toasts(page, 3000), res.splice(0))
}
await makeLot('บริษัท ยูเอที ลิสซิ่ง จำกัด', 'CO1')
log('probe mix CO1+007:', await post(page, '/api/handover-lots', { companyId: CO1, type: 'finance_pickup', scheduledAt: `${SCHED}:00+07:00`, assetIds: [A007] }))
await makeLot('บริษัท ยูเอที แคปปิตอล จำกัด', 'CO2')
await page.goto(`${BASE}/warehouse`); await settle(page)
await page.getByRole('tab', { name: /^รอส่งมอบ/ }).click(); await sleep(900)
log('pending lots', (await page.locator('main').innerText()).replace(/\s*\n+\s*/g, ' | ').slice(0, 900))
await shot(page, R, '18-lots-pending', { fullPage: true })
for (const [i, pdf] of [[0, 'R5-LOT-CO1-signed-v2.pdf'], [0, 'R5-LOT-CO2-signed.pdf']]) {
  await page.goto(`${BASE}/warehouse`); await settle(page)
  await page.getByRole('tab', { name: /^รอส่งมอบ/ }).click(); await sleep(900)
  await page.getByRole('button', { name: 'แนบเอกสาร', exact: true }).nth(i).click(); await sleep(1000)
  const dlg = page.locator('[role="dialog"]').last()
  const head = (await dlg.innerText()).split('\n')[0]
  await dlg.locator('label', { hasText: /เลือกไฟล์|แนบไฟล์ใหม่แทน/ }).nth(0).locator('input[type=file]').setInputFiles(F(pdf))
  log('attach', head, await toasts(page, 3000)); await sleep(1500); await settle(page)
  const btn = dlg.getByRole('button', { name: 'ยืนยันส่งมอบสำเร็จ' })
  log('confirm disabled?', await btn.isDisabled())
  await shot(page, R, `18-confirm-${pdf.includes('CO1') ? 'co1' : 'co2'}`)
  await btn.click()
  log('confirm', head, await toasts(page, 4000), res.splice(0))
  await sleep(1000)
}
await page.goto(`${BASE}/warehouse`); await settle(page)
await page.getByRole('tab', { name: /^ส่งมอบแล้ว/ }).click(); await sleep(1000)
log('delivered', (await page.locator('main').innerText()).replace(/\s*\n+\s*/g, ' | ').slice(0, 900))
await shot(page, R, '18-lots-confirmed', { fullPage: true })
log('5xx', serverErrors)
await browser.close()
log(q(`select l.lot_number,l.delivery_note_number,l.status,l.signed_doc_url,(select string_agg(c.case_ref||':'||a.asset_status,',') from assets a join cases c on c.id=a.case_id where a.lot_id=l.id) from handover_lots l where l.created_at>'${T}' order by 1`))
log(q(`select c.case_ref,x.expense_type,x.gross_satang,x.status from expenses x join cases c on c.id=x.case_id where c.case_ref in ('UAT-CO1-901','UAT-CO2-007') order by 1,2`))
log(q(`select count(*) revenues_new from revenues where created_at>'${T}'`))
log(q(`select u.username,n.event_code,n.title,n.body from notifications n join users u on u.id=n.user_id where n.created_at>'${T}' order by n.created_at`))
