// R13.23 ยกเลิกรอบ (ยังไม่สร้างไฟล์) — probe เหตุผลว่าง แล้วยกเลิกจริง
import { openAs, shot, log, settle, sleep, R, q, BASE, toasts, trackMutations } from './_h.mjs'
const NAME = 'UAT IN-R13a', ID = 'c23b1842-9aba-4847-83ed-88cc9ca761a0'
const flat = s => s.replace(/\s*\n+\s*/g, ' | ')
const { browser, page } = await openAs('uat.finance')
const m = trackMutations(page)
await page.goto(`${BASE}/finance?tab=payout`); await settle(page); await sleep(1000)
const row = page.locator('tbody tr').filter({ hasText: NAME })
log('row buttons', await row.getByRole('button').allInnerTexts())
await row.getByRole('button', { name: 'ดูรายการ' }).click(); await sleep(1500)
log('detail buttons', await page.locator('[role="dialog"]').last().getByRole('button').allInnerTexts())
await page.locator('[role="dialog"]').last().getByRole('button', { name: /ยกเลิกรอบ/ }).first().click(); await sleep(900)
const d = page.locator('[role="dialog"]').last()
log('cancel modal', flat(await d.innerText()).slice(0, 700))
const cbtn = d.getByRole('button', { name: /ยืนยัน|ยกเลิกรอบ/ }).last()
log('confirm disabled (no reason)?', await cbtn.isDisabled())
if (!(await cbtn.isDisabled())) { await cbtn.click(); await sleep(800); log('no-reason click →', flat(await d.innerText()).slice(-300), await toasts(page, 1200), m.res.splice(0)) }
await shot(page, R, '23-cancel-no-reason')
const r0 = await page.request.post(`${BASE}/api/payout-batches/${ID}/cancel`, { data: {}, failOnStatusCode: false })
log('API cancel {}', r0.status(), (await r0.text()).slice(0, 250))
await d.locator('textarea').first().fill('UAT R13 ทดสอบยกเลิกรอบ draft')
const cbs = d.locator('input[type=checkbox]'); log('checkboxes', await cbs.count())
await cbtn.click()
log('cancel toasts', await toasts(page, 3000), m.res.splice(0))
await settle(page); await sleep(800); await shot(page, R, '23-cancelled', { fullPage: true })
await page.goto(`${BASE}/finance?tab=advances`); await settle(page); await sleep(1000)
const ar = page.locator('tbody tr').filter({ hasText: 'ADV-3BDE18D7' })
log('ADV1 row', (await ar.first().innerText().catch(() => '')).replace(/\s+/g, ' ').slice(0, 300))
await shot(page, R, '23-adv1-outstanding-again', { fullPage: true })
await browser.close()
log(q(`select name,status,cancelled_at is not null c_at,cancelled_by is not null c_by,cancel_reason from payout_batches where id='${ID}'`))
log(q(`select count(*) items_left from payout_batch_items where payout_batch_id='${ID}'`))
log(q(`select count(*) filter (where payout_batch_item_id is not null) linked, count(*) from expenses x join payee_profiles p on p.id=x.payee_id join users u on u.id=p.user_id where u.username='uat.agent.in1' and x.status='approved'`))
log(q(`select channel,amount_satang,reversed_at is not null rev,reversal_reason from advance_returns where payout_batch_id='${ID}'`))
log(q(`select action,reason from audit_logs where target_id='${ID}' order by created_at`))
log(q(`select count(*) wht_new from wht_certificates where created_at>now()-interval '30 min'`))
