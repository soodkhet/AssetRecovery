import { openAs, shot, BASE, fillCaseForm, collect, trackApi, log, q, SQL, settle, sleep, rowText, checkDocs, CASES } from './_h.mjs'
const { browser, page, consoleErrors, serverErrors } = await openAs('uat.admin')
const api = trackApi(page)
const txtReqs = []
page.on('request', r => { if (r.url().includes('not-an-image') || (r.postData() ?? '').includes('not-an-image')) txtReqs.push(r.url()) })
await page.goto(`${BASE}/cases/submit`); await settle(page)
const dlg = page.getByRole('dialog')
async function createAndSubmit(key, step, probeTxt = false) {
  const c = CASES[key]; log(`== ${step} ${key} ${c.ref}`)
  await page.getByRole('button', { name: '+ รับเคส (กรอกมือ)' }).click()
  await dlg.waitFor(); await sleep(600)
  if (probeTxt) {
    // กรอกส่วนบนก่อน แล้ว probe ไฟล์ .txt ในช่องรูปสินค้า
    await fillCaseForm(page, dlg, key, { files: {} })
    await dlg.locator('input[type=file]').nth(3).setInputFiles('uat/fixtures/files/not-an-image.txt')
    await sleep(800)
    const t = (await dlg.innerText()).replace(/\s+/g, ' ')
    const k = t.indexOf('ไฟล์บางรายการ'); log('txt probe alert', k >= 0 ? t.slice(k, k + 200) : 'NO ALERT FOUND')
    const j = t.indexOf('รูปสินค้า 0/8'); log('product slot', j >= 0 ? t.slice(j, j + 60) : t.slice(t.indexOf('รูปสินค้า'), t.indexOf('รูปสินค้า') + 120))
    await dlg.locator('input[type=file]').nth(3).scrollIntoViewIfNeeded().catch(() => {})
    await shot(page, 'R2', `${step}-${key.toLowerCase()}-txt-rejected`)
    const fi = dlg.locator('input[type=file]'), n = key.slice(1)
    await fi.nth(0).setInputFiles(`uat/fixtures/files/C${n}-contract.pdf`)
    await fi.nth(1).setInputFiles(`uat/fixtures/files/C${n}-idcard.png`)
    await fi.nth(3).setInputFiles(`uat/fixtures/files/C${n}-product.png`)
  } else {
    await fillCaseForm(page, dlg, key)
  }
  const provIdc = await dlg.locator('select[id$="-province"]').nth(2).inputValue()
  log('idcard province now', provIdc)
  await sleep(300)
  await shot(page, 'R2', `${step}-${key.toLowerCase()}-form`, { fullPage: true })
  await dlg.getByRole('button', { name: 'บันทึกเคสร่าง' }).click()
  log('toasts', (await collect(page, 6500)).filter(s => !s.startsWith('ALERT เลขที่สัญญาห้ามซ้ำ')))
  if (await dlg.isVisible().catch(() => false)) { log('!! dialog still open', (await dlg.innerText()).replace(/\s+/g, ' ').slice(0, 300)); return }
  await settle(page)
  const resP = page.waitForResponse(x => x.url().includes('/status') && x.request().method() === 'PATCH')
  await page.locator('tr', { hasText: c.ref }).first().getByRole('button', { name: 'ส่งตรวจสอบเคส' }).click()
  const res = await resP; log('PATCH', res.status())
  log('toasts', await collect(page, 2500))
  await settle(page)
  log('row', await rowText(page, c.ref))
  await shot(page, 'R2', `${step}-${key.toLowerCase()}-submitted`)
  log(q(`select c.status,c.asset_kind,c.imei,c.debt_amount_satang debt,c.projected_revenue_satang proj,st.name sugg,c.addr_province,c.id_card_addr_province from cases c left join teams st on st.id=c.suggested_team_id where case_ref='${c.ref}'`))
  log(checkDocs(c.ref))
}
await createAndSubmit('C3', 'R2.08', true)
log('txt requests', txtReqs)
await createAndSubmit('C4', 'R2.09')
await createAndSubmit('C5', 'R2.10')
await createAndSubmit('C7', 'R2.11')
await createAndSubmit('C8', 'R2.12')
log('non-2xx api', api.filter(s => !/^20[01] /.test(s)))
log('console', consoleErrors, 'server5xx', serverErrors)
await browser.close()
