import { openAs, shot, BASE, fillCaseForm, trackUploads, toasts, log, q, SQL, settle, sleep } from './_h.mjs'
const { browser, page, consoleErrors, serverErrors } = await openAs('uat.admin')
const up = trackUploads(page)
// R2.01
await page.goto(`${BASE}/cases/submit`); await settle(page)
log('== R2.01 url', page.url())
log('h1', await page.locator('h1').first().innerText())
log('main text', (await page.locator('main').first().innerText()).replace(/\s+/g, ' ').slice(0, 700))
log('th', (await page.locator('th').allInnerTexts()).join(' | '))
await shot(page, 'R2', 'R2.01-empty-list')
// R2.02
log('== R2.02')
await page.getByRole('button', { name: '+ รับเคส (กรอกมือ)' }).click()
const dlg = page.getByRole('dialog'); await dlg.waitFor(); await sleep(600)
const r = await fillCaseForm(page, dlg, 'C1', { files: { contract: true, product: true } })
log('lookup prov', r.gotProv)
await sleep(500)
await shot(page, 'R2', 'R2.02-c1-form', { fullPage: true })
// also screenshot dialog scrolled to attachments
await dlg.locator('input[type=file]').nth(0).scrollIntoViewIfNeeded().catch(() => {})
await shot(page, 'R2', 'R2.02-c1-form-attach')
await dlg.getByRole('button', { name: 'บันทึกเคสร่าง' }).click()
await sleep(6000)
log('toasts', await toasts(page, 500))
log('dialog visible', await dlg.isVisible().catch(() => false))
if (await dlg.isVisible().catch(() => false)) log('dlg alerts', (await dlg.innerText()).replace(/\s+/g,' ').slice(0,400))
await settle(page)
const row = page.locator('tr', { hasText: 'UAT-CO1-001' })
log('row', (await row.innerText().catch(() => 'NO ROW')).replace(/\s+/g, ' '))
await shot(page, 'R2', 'R2.02-c1-done')
log('uploads', up)
log('console', consoleErrors, 'server5xx', serverErrors)
log(q(SQL.caseRow('UAT-CO1-001')))
log(q(SQL.snap('UAT-CO1-001')))
log(q(SQL.docs('UAT-CO1-001')))
log(q(SQL.audit('UAT-CO1-001')))
await browser.close()
