async function submitRow(ref, slug) {
  const resP = page.waitForResponse(x => x.url().includes('/status') && x.request().method() === 'PATCH')
  await page.locator('tr', { hasText: ref }).first().getByRole('button', { name: 'ส่งตรวจสอบเคส' }).click()
  const res = await resP
  log('PATCH', res.status(), JSON.stringify(await res.json()).slice(0, 330))
  log('toasts', await collect(page, 2500))
  await shot(page, 'R2', slug)
  await settle(page)
  log('row', await rowText(page, ref))
}
