import { openAs, shot, BASE, fillCaseForm, collect, trackApi, log, q, SQL, settle, sleep, rowText, checkDocs } from './_h.mjs'
const { browser, page, consoleErrors, serverErrors } = await openAs('uat.admin')
const api = trackApi(page)
log('######## ATTEMPT 2 start', new Date().toISOString())
await page.goto(`${BASE}/cases/submit`); await settle(page)
log('== R2.01 url', page.url())
log('main', (await page.locator('main').first().innerText()).replace(/\s+/g, ' ').slice(0, 600))
log('th', (await page.locator('th').allInnerTexts()).join(' | '))
await shot(page, 'R2', 'R2.01-empty-list')
log('== R2.02')
await page.getByRole('button', { name: '+ รับเคส (กรอกมือ)' }).click()
const dlg = page.getByRole('dialog'); await dlg.waitFor(); await sleep(600)
log('dlg title', await dlg.locator('h2').first().innerText().catch(() => '?'))
const r = await fillCaseForm(page, dlg, 'C1', { files: { contract: true, product: true } })
log('lookup prov', r.gotProv)
await sleep(500)
await shot(page, 'R2', 'R2.02-c1-form', { fullPage: true })
await dlg.locator('input[type=file]').nth(0).scrollIntoViewIfNeeded().catch(() => {})
await shot(page, 'R2', 'R2.02-c1-form-attach')
await dlg.getByRole('button', { name: 'บันทึกเคสร่าง' }).click()
log('toasts', await collect(page, 7000))
log('dialog visible', await dlg.isVisible().catch(() => false))
await settle(page)
log('row', await rowText(page, 'UAT-CO1-001'))
await shot(page, 'R2', 'R2.02-c1-done')
log('api', api.splice(0))
log(q(SQL.caseRow('UAT-CO1-001')))
log(q(SQL.snap('UAT-CO1-001')))
log(q(`select source,serial_no,suggested_team_id,assigned_team_id from cases where case_ref='UAT-CO1-001'`))
log(checkDocs('UAT-CO1-001'))
log(q(SQL.audit('UAT-CO1-001')))
// R2.03
log('== R2.03')
const row = page.locator('tr', { hasText: 'UAT-CO1-001' }).first()
const resP = page.waitForResponse(x => x.url().includes('/status') && x.request().method() === 'PATCH')
await row.getByRole('button', { name: 'ส่งตรวจสอบเคส' }).click()
const res = await resP
log('PATCH', res.status(), JSON.stringify(await res.json()).slice(0, 400))
log('toasts', await collect(page, 2500))
await shot(page, 'R2', 'R2.03-c1-doc-incomplete')
await settle(page)
log('row', await rowText(page, 'UAT-CO1-001'))
log(q(`select status,projected_revenue_satang from cases where case_ref='UAT-CO1-001'`))
log(q(`select count(*) status_change from audit_logs where action='status_change' and target_id=(select id from cases where case_ref='UAT-CO1-001')`))
log('console', consoleErrors, 'server5xx', serverErrors)
await browser.close()
