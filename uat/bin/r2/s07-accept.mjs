import { openAs, shot, BASE, collect, log, q, SQL, settle, sleep, rowText, CASES, TEAM_B } from './_h.mjs'
const ids = Object.fromEntries(q(`select case_ref||'='||id from cases`).split('\n').filter(l => l.includes('=') && l.includes('UAT')).map(l => l.trim().split('=')))
const { browser, page, consoleErrors, serverErrors } = await openAs('uat.approver')
await page.goto(`${BASE}/cases/submit`); await settle(page)
log('== R2.21 API probe teamId without reason')
const r = await page.request.patch(`${BASE}/api/cases/${ids['UAT-CO1-002']}/status`, { data: { action: 'accept', teamId: TEAM_B } })
log('probe', r.status(), (await r.text()).slice(0, 300))
log(q(`select status,assigned_team_id,service_fee_template_id from cases where case_ref='UAT-CO1-002'`))
log(q(`select count(*) approve from audit_logs where action='approve' and target_id='${ids['UAT-CO1-002']}'`))
async function accept(key, step) {
  const c = CASES[key]; log(`== ${step} ${key} ${c.ref}`)
  await page.locator('tr', { hasText: c.ref }).first().getByRole('button', { name: 'พิจารณา' }).click()
  const dlg = page.getByRole('dialog').filter({ hasText: `เคส ${c.ref} · รอบที่ 1` }).first(); await dlg.waitFor(); await sleep(1500)
  const t = (await dlg.innerText()).replace(/\s+/g, ' ')
  const a = t.indexOf('ประมาณการรายได้'); log('projected box', t.slice(a, a + 60))
  const b = t.indexOf('ทีมที่เสนอ'); log('team box', t.slice(b, b + 110))
  await shot(page, 'R2', `${step}-${key.toLowerCase()}-review`)
  const resP = page.waitForResponse(x => x.url().includes('/status') && x.request().method() === 'PATCH')
  await dlg.getByRole('button', { name: 'รับเคส & ยืนยันทีม', exact: true }).click()
  const res = await resP; log('PATCH', res.status())
  log('toasts', await collect(page, 2000))
  await settle(page)
  log('row', await rowText(page, c.ref))
  await shot(page, 'R2', `${step}-${key.toLowerCase()}-approved`)
  log(q(`select c.status,at.name assigned,c.projected_revenue_satang proj,t.name tpl,t.version v,c.service_fee_model_snapshot m,c.service_fee_base_satang base,c.service_fee_rate_pct rate,c.service_fee_basis_snapshot basis,c.service_fee_charge_on_fail cof from cases c left join teams at on at.id=c.assigned_team_id left join service_fee_templates t on t.id=c.service_fee_template_id where case_ref='${c.ref}'`))
  log(q(`select action,reason from audit_logs where action='approve' and target_id='${ids[c.ref]}'`))
  log(q(`select count(*) noti, max(body) body from notifications where event_code='case.approved' and body like 'เคส ${c.ref}%'`))
}
await accept('C2', 'R2.21')
await accept('C3', 'R2.22')
await accept('C4', 'R2.23')
await accept('C5', 'R2.24')
log('console', consoleErrors, 'server5xx', serverErrors)
await browser.close()
