log('R1.22 outsource rows', JSON.stringify(await rows()))
await shot(page, 'R1', 'R1.22-users-outsource', { fullPage: true })
await page.getByRole('tab', { name: /บริษัทไฟแนนซ์/ }).click(); await settle(page)
log('R1.22 company rows', JSON.stringify(await rows()))
log('R1.22 row buttons (company first row)', JSON.stringify(await page.locator('tbody tr').first().getByRole('button').allInnerTexts()))
await shot(page, 'R1', 'R1.22-users-company', { fullPage: true })
log('consoleErrors', s.consoleErrors, 'serverErrors', s.serverErrors)
await s.browser.close()
