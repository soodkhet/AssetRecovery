import { openAs, shot, BASE, toasts, inlineErrors, trackMutations, settle, log, sleep } from './_h.mjs'
const s = await openAs('admin')
const { page } = s
const m = trackMutations(page)
// R1.20 companies user count
await page.goto(`${BASE}/settings/companies`); await settle(page)
log('R1.20 counts', JSON.stringify((await page.locator('main').innerText()).match(/\d+ บัญชีผู้ใช้/g)))
await shot(page, 'R1', 'R1.20-companies-usercount', { fullPage: true })
// R1.21 dup username
await page.goto(`${BASE}/settings/users`); await settle(page)
await page.getByRole('button', { name: '+ สร้างบัญชี' }).click()
const dlg = page.getByRole('dialog')
await dlg.locator('#user-group').selectOption('inhouse')
await dlg.locator('#user-role').selectOption({ label: 'พนักงานติดตามทรัพย์' })
await dlg.locator('#user-name').fill('ทดสอบ ชื่อซ้ำ')
await dlg.locator('#user-username').fill('UAT.Agent.In1')
const pw = 'Dup' + Math.random().toString(36).slice(2, 8) + '9z'
await dlg.locator('#user-password').fill(pw)
await dlg.locator('#user-confirm-password').fill(pw)
await dlg.locator('#user-team').selectOption({ label: 'UAT ทีม A กรุงเทพ (inhouse)' })
log('R1.21 username value after fill', await dlg.locator('#user-username').inputValue())
await dlg.getByRole('button', { name: 'สร้างบัญชี', exact: true }).click()
log('R1.21 toast', JSON.stringify(await toasts(page)), 'res', m.res, 'dialog open', await dlg.isVisible(), 'inline', await inlineErrors(dlg))
await shot(page, 'R1', 'R1.21-dup-username', { fullPage: true })
if (await dlg.isVisible()) await dlg.getByRole('button', { name: 'ยกเลิก' }).click()
// R1.22 tabs
await page.reload(); await settle(page)
const tabs = await page.getByRole('tab').allInnerTexts()
log('R1.22 tabs', JSON.stringify(tabs))
const rows = async () => (await page.locator('tbody tr').allInnerTexts()).map(r => r.replace(/\s+/g, ' ').slice(0, 160))
await page.getByRole('tab', { name: /แอดมิน/ }).click(); await settle(page)
log('R1.22 admin rows', JSON.stringify(await rows(), null, 0))
await shot(page, 'R1', 'R1.22-users-admin', { fullPage: true })
await page.getByRole('tab', { name: /เจ้าหน้าที่ติดตามทรัพย์/ }).click(); await settle(page)
await page.getByRole('button', { name: 'Inhouse', exact: true }).click().catch(e => log('no Inhouse btn', e.message)); await settle(page)
log('R1.22 inhouse rows', JSON.stringify(await rows()))
await shot(page, 'R1', 'R1.22-users-inhouse', { fullPage: true })
