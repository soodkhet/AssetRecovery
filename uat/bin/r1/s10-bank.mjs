import { openAs, shot, BASE, toasts, inlineErrors, fields, trackMutations, settle, log, sleep } from './_h.mjs'
const s = await openAs('admin')
const { page } = s
const m = trackMutations(page)
const body = () => page.locator('main').first()
await page.goto(`${BASE}/settings/finance?tab=approval`); await settle(page)
await page.getByRole('button', { name: /เพิ่มกติกา/ }).first().click()
let dlg = page.getByRole('dialog')
await dlg.getByRole('button', { name: 'เพิ่มกติกา', exact: true }).click(); await sleep(700)
log('R1.26 probe errors', JSON.stringify(await inlineErrors(dlg)), 'mut', m.reqs)
await dlg.getByRole('button', { name: 'ยกเลิก' }).click()
log('R1.28 last edited', (await body().innerText()).match(/แก้ไขล่าสุด[^\n]*/g)?.slice(-1)[0], 'nested main count', await page.locator('main').count())
await page.locator('#policy-advance-max').scrollIntoViewIfNeeded()
await shot(page, 'R1', 'R1.28-policy-done', { fullPage: true })

// R1.29 bank account
await page.goto(`${BASE}/settings/finance?tab=bank`); await settle(page)
await page.getByRole('button', { name: /เพิ่มบัญชี/ }).first().click()
dlg = page.getByRole('dialog')
log('R1.29 fields\n  ' + await fields(dlg))
const sel = async (id, txt) => { const o = await dlg.locator(id + ' option').allInnerTexts(); log(id, JSON.stringify(o)); await dlg.locator(id).selectOption({ label: o.find(x => x.includes(txt)) }) }
const bankTag = await dlg.locator('#bank-account-bank').evaluate(e => e.tagName)
if (bankTag === 'SELECT') await sel('#bank-account-bank', 'กสิกร'); else await dlg.locator('#bank-account-bank').fill('กสิกรไทย')
await dlg.locator('#bank-account-name').fill('บริษัท แอสเซ็ท รีคัฟเวอรี่ (UAT) จำกัด')
await dlg.locator('#bank-account-number').fill('9990001112')
await sel('#bank-account-type', 'ออมทรัพย์')
await sel('#bank-account-usage', 'Both')
await dlg.locator('#bank-account-tolerance').fill('7')
log('statement/payment-file', await dlg.locator('#bank-account-statement').evaluate(e => e.tagName + ' ' + [...(e.options ?? [])].map(o => o.text).join('|')), await dlg.locator('#bank-account-payment-file').evaluate(e => e.tagName + ' ' + [...(e.options ?? [])].map(o => o.text).join('|')))
log('checkboxes', JSON.stringify(await dlg.getByRole('checkbox').evaluateAll(els => els.map(e => (e.closest('label')?.innerText ?? '').trim() + '=' + e.checked))))
await dlg.getByRole('checkbox', { name: /บัญชีหลัก/ }).check()
const payout = dlg.getByRole('checkbox', { name: /จ่าย|payout/i })
if (await payout.count()) await payout.first().check()
await dlg.locator('#bank-account-reason').fill('เพิ่มบัญชีธนาคารหลักของบริษัทสำหรับ UAT รอบที่ 1')
await shot(page, 'R1', 'R1.29-bank-account-form', { fullPage: true })
await dlg.getByRole('button', { name: 'เพิ่มบัญชี', exact: true }).click()
log('R1.29 toast', JSON.stringify(await toasts(page)), 'res', m.res, 'open', await dlg.isVisible())
if (await dlg.isVisible()) { log('errors', await inlineErrors(dlg)); await dlg.getByRole('button', { name: 'ยกเลิก' }).click() }
await settle(page); await sleep(1000)
log('R1.29 table', JSON.stringify((await page.locator('tbody tr').allInnerTexts()).map(x => x.replace(/\s+/g, ' ').slice(0, 200))))
await shot(page, 'R1', 'R1.29-bank-account-done', { fullPage: true })

// R1.30 bank file
await page.goto(`${BASE}/settings/finance?tab=bankfile`); await settle(page)
await page.getByRole('button', { name: /เพิ่มรูปแบบไฟล์/ }).first().click()
dlg = page.getByRole('dialog')
log('R1.30 fields\n  ' + await fields(dlg))
const bt = await dlg.locator('#bank-file-bank').evaluate(e => e.tagName)
if (bt === 'SELECT') await sel('#bank-file-bank', 'กสิกร'); else await dlg.locator('#bank-file-bank').fill('กสิกรไทย')
await sel('#bank-file-type', 'CSV')
await sel('#bank-file-encoding', 'UTF-8')
log('R1.30 columns default', JSON.stringify(await dlg.locator('#bank-file-columns').inputValue().catch(() => null)), 'buttons', JSON.stringify(await dlg.getByRole('button').allInnerTexts()))
await dlg.locator('#bank-file-reason').fill('เพิ่มรูปแบบไฟล์โอนธนาคารกสิกรไทยสำหรับ UAT รอบที่ 1')
await shot(page, 'R1', 'R1.30-bankfile-form', { fullPage: true })
await dlg.getByRole('button', { name: 'เพิ่มรูปแบบไฟล์', exact: true }).click()
log('R1.30 toast', JSON.stringify(await toasts(page)), 'res', m.res.slice(-1), 'open', await dlg.isVisible())
if (await dlg.isVisible()) { log('errors', await inlineErrors(dlg)) ; await shot(page, 'R1', 'R1.30-bankfile-error', { fullPage: true }) }
else { await settle(page); log('R1.30 table', JSON.stringify((await page.locator('tbody tr').allInnerTexts()).map(x => x.replace(/\s+/g, ' ').slice(0, 250)))); await shot(page, 'R1', 'R1.30-bankfile-done', { fullPage: true }) }
log('consoleErrors', s.consoleErrors, 'serverErrors', s.serverErrors)
await s.browser.close()
