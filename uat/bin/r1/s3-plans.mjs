  IN: { name: 'UAT Inhouse', side: 'inhouse', daily: '200.00', allowance: '150.00', hotel: '800.00', commission: '500.00', noSuccess: '200.00', wht: '3.00', eff: '2026-10-01', reason: 'ตั้งแผนค่าตอบแทนทีม Inhouse สำหรับ UAT รอบที่ 1' },
  OUT: { name: 'UAT Outsource เหมา', side: 'outsource', daily: '5,500.00', allowance: '0', hotel: '0', commission: '1,000.00', noSuccess: '0', wht: '5.00', eff: '2026-10-01', reason: 'ตั้งแผนค่าตอบแทนทีม Outsource แบบเหมาสำหรับ UAT รอบที่ 1' },
