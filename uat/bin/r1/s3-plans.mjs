async function fill(dlg, p) {
  await dlg.locator('#plan-name').fill(p.name)
  await dlg.locator('#plan-side').selectOption(p.side)
  await dlg.getByRole('button', { name: 'เหมาจ่ายรายวัน' }).click()
  await dlg.locator('#fuel-daily').fill(p.daily)
  await dlg.locator('#plan-allowance').fill(p.allowance)
  await dlg.locator('#plan-hotel').fill(p.hotel)
  await dlg.locator('#plan-commission').fill(p.commission)
  await dlg.locator('#plan-no-success').fill(p.noSuccess)
  await dlg.locator('#plan-wht').fill(p.wht)
  await dlg.locator('#plan-effective').fill(p.eff)
  const cb = dlg.getByRole('checkbox', { name: /บังคับแนบใบเสร็จ/ })
  log('receipt checkbox default', await cb.isChecked())
  await cb.check()
  await dlg.locator('#plan-reason').fill(p.reason)
}
