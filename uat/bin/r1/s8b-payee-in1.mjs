import { openAs, shot, BASE, toasts, inlineErrors, trackMutations, settle, log, sleep } from './_h.mjs'
const s = await openAs('admin')
const { page } = s
const m = trackMutations(page)
await page.goto(`${BASE}/settings/finance?tab=payee`); await settle(page)
await page.getByRole('button', { name: /เพิ่ม Payee/ }).click()
const dlg = page.getByRole('dialog')
await page.waitForFunction(() => document.querySelectorAll('#payee-user option').length > 1, null, { timeout: 15000 })
const uo = await dlg.locator('#payee-user option').allInnerTexts()
log('user opts', JSON.stringify(uo))
await dlg.locator('#payee-user').selectOption({ label: uo.find(o => o.startsWith('อนันต์ ตามทรัพย์')) })
await dlg.locator('#payee-type').selectOption({ label: 'บุคคลธรรมดา' })
await dlg.locator('#payee-national-id').fill('1103700000011')
const to = await dlg.locator('#payee-tax-profile option').allInnerTexts()
await dlg.locator('#payee-tax-profile').selectOption({ label: to.find(o => o.startsWith('Outsource Standard 3%')) })
await dlg.locator('#payee-bank').fill('กสิกรไทย')
await dlg.locator('#payee-account-name').fill('อนันต์ ตามทรัพย์')
await dlg.locator('#payee-account-number').fill('1234567810')
await dlg.locator('#payee-reason').fill('เพิ่มข้อมูลผู้รับเงิน อนันต์ ตามทรัพย์ สำหรับ UAT รอบที่ 1')
await shot(page, 'R1', 'R1.25-payee-form', { fullPage: true })
await dlg.getByRole('button', { name: 'เพิ่มผู้รับเงิน', exact: true }).click()
log('toast', JSON.stringify(await toasts(page)), 'res', m.res, 'open', await dlg.isVisible())
if (await dlg.isVisible()) { log('errors', await inlineErrors(dlg)); await dlg.getByRole('button', { name: 'ยกเลิก' }).click() }
await settle(page); await sleep(1500)
log('table', JSON.stringify((await page.locator('tbody tr').allInnerTexts()).map(x => x.replace(/\s+/g, ' ').slice(0, 200))))
await shot(page, 'R1', 'R1.25-payees-done', { fullPage: true })
log('consoleErrors', s.consoleErrors, 'serverErrors', s.serverErrors)
await s.browser.close()
