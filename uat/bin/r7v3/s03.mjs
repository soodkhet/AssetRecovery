import { openAs, shot, R, ID, CSV, log, q, settle, sleep, mainText, dlgText, waitToast, BASE } from './_h.mjs'
log('=== R7.03', new Date().toISOString())
const s = await openAs('uat.account')
const p = s.page
await p.goto(`${BASE}/accounting?tab=bank`); await settle(p)
log('url', p.url()); log('main', await mainText(p, 900))
await shot(p, R, '03a-bank-tab-empty')
await p.getByRole('button', { name: /Import Statement/ }).click(); await sleep(600)
const d = p.locator('[role="dialog"]').last()
const sel = d.locator('select').first()
log('options', await sel.locator('option').allInnerTexts())
await sel.selectOption(ID.BANK)
await d.locator('input[type=file]').setInputFiles(CSV); await sleep(400)
log('dlg', await dlgText(p, 900))
await shot(p, R, '03b-import-modal')
const resps = []
p.on('response', async r => { if (r.url().includes('/api/bank-reconciliation/import')) { let b=''; try { b = await r.text() } catch {} resps.push(`${r.status()} ${b.slice(0,700)}`) } })
await d.getByRole('button', { name: 'อัปโหลดและประมวลผล' }).dblclick().catch(e => log('dbl err', e.message))
const t = await waitToast(p, 15000); log('toast', t)
await sleep(2500); log('resps', resps)
await shot(p, R, '03c-import-toast')
await settle(p); await sleep(800)
log('main after', await mainText(p, 1600))
await shot(p, R, '03d-bank-after-import', { fullPage: true })
log(q(`select transaction_date, amount_satang, match_status, matched_billing_id is not null b, matched_payout_id is not null p, left(description,60) d from bank_transactions order by amount_satang`))
log('errs', s.consoleErrors.slice(0,3), s.serverErrors)
await s.browser.close()
