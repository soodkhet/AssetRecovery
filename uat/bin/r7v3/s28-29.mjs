// R7.28 สร้าง exception critical · R7.29 readiness ไม่ผ่าน + send/export ถูกปัด (uat.account)
import { openAs, shot, R, ID, log, q, q1, settle, sleep, waitToast, mainText, dlgText, BASE, api, guard2xx, auditSince } from './_h.mjs'
log('=== R7.28-29', new Date().toISOString())
const T = q1('select now()'); log('T', T)
const s = await openAs('uat.account'); const p = s.page
await p.goto(`${BASE}/accounting?tab=documents`); await settle(p); await sleep(1000)
log('28 tab', await mainText(p, 900))
await shot(p, R, '28a-exceptions-empty')
await p.locator('main').getByRole('button', { name: 'บันทึกข้อยกเว้น' }).click(); await sleep(700)
const d = p.locator('[role="dialog"]').last()
log('28 options level', await d.locator('#exception-level option').evaluateAll(o => o.map(x => x.value + '=' + x.textContent)))
log('28 options module', await d.locator('#exception-module option').evaluateAll(o => o.map(x => x.value + '=' + x.textContent)))
log('28 options period', await d.locator('select').nth(2).locator('option').evaluateAll(o => o.map(x => x.value.slice(0, 8) + '=' + x.textContent)).catch(() => '-'))
await d.locator('#exception-level').selectOption('critical')
await d.locator('#exception-module').selectOption('expense').catch(e => log('module err', e.message.slice(0, 80)))
await d.locator('#exception-title').fill('UAT R7 ใบเสร็จค่าที่พักต้นฉบับยังไม่ส่งสำนักงานบัญชี')
await d.locator('#exception-description').fill('ต้องส่งต้นฉบับใบเสร็จโรงแรมของ in1 ฿600 ก่อนปิดงวด')
log('28 dlg', await dlgText(p, 1200))
await shot(p, R, '28b-exception-form')
const rp = p.waitForResponse(r => r.url().includes('/api/exceptions') && r.request().method() === 'POST', { timeout: 15000 })
await d.getByRole('button', { name: 'บันทึกข้อยกเว้น' }).click()
const resp = await rp; log('28 resp', resp.status(), JSON.stringify(await resp.json()).slice(0, 400))
log('28 toast', await waitToast(p)); await settle(p); await sleep(800)
log('28 after', await mainText(p, 1400))
await shot(p, R, '28c-exception-open', { fullPage: true })
log('28 sql', q("select level, status, module, title, period_id is not null has_period, (select year_be||'-'||month from accounting_periods ap where ap.id=e.period_id) per, created_at from exceptions e"))
// R7.29
await p.goto(`${BASE}/accounting?tab=closing`); await settle(p); await sleep(1000)
log('29 closing', await mainText(p, 1600))
await shot(p, R, '29a-closing-tab-blocked', { fullPage: true })
await p.locator('main').getByRole('button', { name: 'ตรวจความพร้อม' }).first().click(); await sleep(1500)
log('29 readiness dlg', await dlgText(p, 1600))
await shot(p, R, '29b-readiness-fail-2')
await p.locator('[role="dialog"]').last().getByRole('button', { name: 'ปิดหน้าต่าง' }).click(); await sleep(400)
log('29 readiness api', await api(p, 'GET', `/api/accounting/periods/${ID.PERIOD}/readiness`))
const sd = await api(p, 'PATCH', `/api/accounting/periods/${ID.PERIOD}/send`, { reason: 'probe' }); log('29 send probe', sd); guard2xx('send', sd)
const ex = await api(p, 'POST', '/api/accounting/export-pack', { periodId: ID.PERIOD }); log('29 export probe', ex); guard2xx('export', ex)
// UI ปุ่มส่ง (ดูว่าซ่อน/ปิด/โชว์อะไร)
log('29 send btn', await p.locator('main').getByRole('button', { name: 'ส่งสำนักงานบัญชี' }).count())
log('29 sql', q("select status, sent_at from accounting_periods where year_be=2569 and month=10"), q('select count(*) exp_rec from export_records'))
log('29 audit', q(auditSince(T)))
log('errs', s.consoleErrors.slice(0, 4), s.serverErrors)
await s.browser.close()
