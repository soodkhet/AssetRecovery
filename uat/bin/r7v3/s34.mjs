// R7.34 ข้อซักถามนักบัญชี — uat.account ตั้งและตอบเอง (มติ O28)
import { openAs, shot, R, log, q, q1, settle, sleep, waitToast, mainText, dlgText, BASE, auditSince, api, guard2xx } from './_h.mjs'
log('=== R7.34', new Date().toISOString())
const T = q1('select now()'); log('T', T)
const s = await openAs('uat.account'); const p = s.page
await p.goto(`${BASE}/accounting?tab=qa`); await settle(p); await sleep(1000)
log('34 tab', await mainText(p, 1200))
await shot(p, R, '34a-questions-empty', { fullPage: true })
const e1 = await api(p, 'POST', '/api/accounting/questions', { questionText: '   ' }); log('34 คำถามว่าง', e1); guard2xx('q-empty', e1)
await p.locator('main').getByRole('button', { name: 'บันทึกข้อซักถาม' }).click(); await sleep(800)
let d = p.locator('[role="dialog"]').last()
log('34 q dlg', await dlgText(p, 900))
log('34 q btn disabled (ว่าง)', await d.getByRole('button', { name: 'บันทึกข้อซักถาม' }).isDisabled())
await d.locator('textarea').fill('เงินรับ 123.45 บาท ไม่ทราบผู้โอน บันทึกเป็นเงินรับรอตรวจสอบ ถูกต้องหรือไม่')
await shot(p, R, '34b-question-form')
const rq = p.waitForResponse(r => r.url().endsWith('/api/accounting/questions') && r.request().method() === 'POST')
await d.getByRole('button', { name: 'บันทึกข้อซักถาม' }).dblclick()
const qr = await rq; const qj = await qr.json(); log('34 q resp', qr.status(), JSON.stringify(qj).slice(0, 400))
log('34 q toast', await waitToast(p)); await sleep(1500); await settle(p)
await shot(p, R, '34c-question-open', { fullPage: true })
const QID = qj.data?.id ?? q1("select id from accountant_questions order by created_at desc limit 1")
const e2 = await api(p, 'PATCH', `/api/accounting/questions/${QID}/answer`, { answerText: '' }); log('34 คำตอบว่าง', e2); guard2xx('a-empty', e2)
await p.locator('main tr', { hasText: '123.45' }).getByRole('button', { name: 'ตอบคำถาม' }).click(); await sleep(800)
d = p.locator('[role="dialog"]').last()
log('34 a dlg', await dlgText(p, 900))
log('34 a btn disabled (ว่าง)', await d.getByRole('button', { name: 'ส่งคำตอบ' }).isDisabled())
await d.locator('textarea').fill('ถูกต้อง บันทึกเป็นหนี้สินหมุนเวียน-เงินรับรอตรวจสอบ จนกว่าจะทราบที่มา')
await shot(p, R, '34d-answer-form')
const ra = p.waitForResponse(r => r.url().includes(`/questions/${QID}/answer`))
await d.getByRole('button', { name: 'ส่งคำตอบ' }).dblclick()
const ar = await ra; log('34 a resp', ar.status(), JSON.stringify(await ar.json()).slice(0, 400))
log('34 a toast', await waitToast(p)); await sleep(1500); await settle(p)
log('34 tab after', await mainText(p, 1500))
await shot(p, R, '34e-question-answered', { fullPage: true })
const e3 = await api(p, 'PATCH', `/api/accounting/questions/${QID}/answer`, { answerText: 'ตอบซ้ำ probe' }); log('34 ตอบซ้ำ', e3); guard2xx('a-again', e3)
log('34 sql', q("select is_resolved, (select year_be||'-'||month from accounting_periods ap where ap.id=period_id) per, left(question_text,40) qt, left(answer_text,40) at, answered_by is not null ab, answered_at, created_at from accountant_questions"))
log('34 audit', q(auditSince(T)))
log('errs', s.consoleErrors.slice(0, 6), s.serverErrors)
await s.browser.close()
