import { openAs, shot, R, log, settle, sleep, mainText, dlgText, api, BASE } from './_h.mjs'
log('=== R7.04-07 UI', new Date().toISOString())
// การเงิน
const f = await openAs('uat.finance'); const fp = f.page
await fp.goto(`${BASE}/finance?tab=payout`); await settle(fp); await sleep(800)
const in1 = fp.locator('tr, [class*=card]').filter({ hasText: 'UAT IN-1' }).first()
log('IN-1 row', (await in1.innerText().catch(()=>'-')).replace(/\s+/g,' ').slice(0,400))
log('confirm btn', await fp.getByRole('button', { name: /ยืนยันจ่ายแล้ว/ }).count())
await shot(fp, R, '04a-finance-payout-in1-completed')
await fp.goto(`${BASE}/finance?tab=revenue`); await settle(fp); await sleep(800)
log('revenue tab', await mainText(fp, 2500))
log('raw ** count', (await fp.locator('main').innerText()).split('**').length - 1)
await shot(fp, R, '06a-finance-revenue-paid', { fullPage: true })
log('AR aging', await api(fp, 'GET', '/api/ar-aging'))
log('errs F', f.consoleErrors.slice(0,3), f.serverErrors)
await f.browser.close()
// บัญชี
const a = await openAs('uat.account'); const p = a.page
await p.goto(`${BASE}/accounting?tab=wht`); await settle(p); await sleep(800)
log('wht tab', await mainText(p, 2200))
await shot(p, R, '05a-account-wht-tab', { fullPage: true })
await p.goto(`${BASE}/accounting?tab=receipts`); await settle(p); await sleep(800)
log('receipts tab', await mainText(p, 1500))
await shot(p, R, '06b-account-receipts')
await p.goto(`${BASE}/accounting?tab=bank`); await settle(p); await sleep(800)
await p.getByRole('button', { name: 'ยังไม่จับคู่', exact: true }).click().catch(e => log('filter err', e.message)); await settle(p); await sleep(600)
log('unmatched filter rows', await p.locator('tbody tr').count(), (await p.locator('tbody').innerText()).replace(/\s+/g,' ').slice(0,300))
await shot(p, R, '07a-bank-filter-unmatched')
await p.getByRole('button', { name: 'จับคู่ Manual' }).first().click(); await sleep(1500)
log('manual dlg', await dlgText(p, 1500))
await shot(p, R, '07b-manual-match-modal')
await p.locator('[role="dialog"]').last().getByRole('button', { name: 'ยกเลิก' }).click(); await sleep(500)
await p.getByRole('button', { name: 'ทั้งหมด', exact: true }).click().catch(()=>{}); await settle(p); await sleep(500)
await p.getByRole('button', { name: 'ดูการจับคู่' }).first().click(); await sleep(1200)
log('detail dlg', await dlgText(p, 1200))
await shot(p, R, '07c-match-detail-modal')
await p.locator('[role="dialog"]').last().getByRole('button', { name: 'ปิดหน้าต่าง' }).click().catch(e => log('close err', e.message))
log('errs A', a.consoleErrors.slice(0,3), a.serverErrors)
await a.browser.close()
