// R15a.02 Superadmin แก้ข้อมูลองค์กร (ข้อมูลตัวอย่าง: เบอร์โทร/อีเมล/ที่อยู่) + เหตุผล
import { openAs, shot, log, settle, sleep, R, BASE, mainText, toasts, trackMutations, q } from './_h.mjs'
const { browser, page, serverErrors, consoleErrors } = await openAs('admin')
const m = trackMutations(page)
await page.goto(`${BASE}/settings/organization`); await settle(page); await sleep(800)
await page.getByRole('button', { name: 'แก้ไขข้อมูล' }).click()
const dlg = page.getByRole('dialog').last(); await dlg.waitFor(); await sleep(500)
// ลองบันทึกโดยไม่ใส่เหตุผลก่อน (ควรถูกบล็อก)
await dlg.locator('#org-phone').fill('02-000-0000')
await dlg.getByRole('button', { name: 'บันทึก' }).click(); await sleep(1200)
log('no-reason errors', (await dlg.locator('.text-red-600').allInnerTexts()).join(' / '), m.res.splice(0))
await dlg.locator('#org-email').fill('uat-sample@example.com')
await dlg.locator('[id$="-detail"]').fill('99/9 ข้อมูลตัวอย่าง UAT ถ.ทดสอบ')
await dlg.locator('#org-tax-id').fill('0999999999999')
await dlg.locator('[id$="-postal"]').fill('10110'); await sleep(1500)
const pickSub = dlg.locator('select').filter({ hasText: 'เลือกตำบล/แขวง' })
if (await pickSub.count()) await pickSub.first().selectOption({ label: 'คลองตัน · คลองเตย · กรุงเทพมหานคร' }); await sleep(500)
const prov = dlg.locator('select[id$="-province"]')
if ((await prov.inputValue()) === '') await prov.selectOption({ label: 'กรุงเทพมหานคร' })
if ((await dlg.locator('[id$="-district"]').inputValue()) === '') await dlg.locator('[id$="-district"]').fill('คลองเตย')
if ((await dlg.locator('[id$="-subdistrict"]').inputValue()) === '') await dlg.locator('[id$="-subdistrict"]').fill('คลองตัน')
await dlg.locator('#org-reason').fill('UAT R15a ทดสอบแก้ข้อมูลองค์กร — ข้อมูลตัวอย่าง ต้องกรอกจริงก่อนใช้งาน')
await shot(page, R, '02-org-edit-filled', { fullPage: true })
await dlg.getByRole('button', { name: 'บันทึก' }).click()
log('toasts', await toasts(page, 2500), m.res.splice(0))
if (await dlg.isVisible().catch(() => false)) log('!! dialog open', (await dlg.innerText()).replace(/\s+/g, ' ').slice(0, 900))
await settle(page)
log('main', await mainText(page, 1500))
await shot(page, R, '02-org-saved', { fullPage: true })
log(q(`select phone,email,address_detail,address_subdistrict,address_district,address_province,address_postal_code,updated_at from organizations`))
log(q(`select action,target_type,reason,left(before_data::text,300) b,left(after_data::text,400) a,created_at from audit_logs where target_type ilike '%organi%' order by created_at desc limit 2`))
log('5xx', serverErrors, 'console', consoleErrors.slice(0, 3))
await browser.close()
