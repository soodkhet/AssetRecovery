// R15a.05 แท็บ เลขที่เอกสาร: ดู 9 ชนิด + ลองแก้ INV (ล็อก) + LOT ตั้งเลขต่ำกว่าเลขที่ใช้แล้ว (ต้องถูกปฏิเสธ) — ไม่แตะ PV (R15b ใช้อยู่)
import { openAs, shot, log, settle, sleep, R, BASE, toasts, trackMutations, mainText, yearCE, q } from './_h.mjs'
const { browser, page, serverErrors, consoleErrors } = await openAs('admin')
const m = trackMutations(page)
const before = q(`select doc_type,prefix,include_year,digits,reset_yearly,current_seq,updated_at from document_number_series order by doc_type`)
await page.goto(`${BASE}/settings/finance?tab=numbering`); await settle(page); await sleep(1000)
const t = await mainText(page, 4000); log('main', t); log('CE', yearCE(t))
log('rows', (await page.locator('tbody tr').allInnerTexts()).map(s => s.replace(/\s+/g, ' ')))
await shot(page, R, '05-numbering-list', { fullPage: true })
// INV
await page.locator('tbody tr', { hasText: 'INV' }).first().getByRole('button', { name: 'แก้ไข' }).click()
let dlg = page.getByRole('dialog').last(); await dlg.waitFor(); await sleep(500)
log('INV dialog', (await dlg.innerText()).replace(/\s+/g, ' ').slice(0, 900))
log('INV disabled', await dlg.locator('input:disabled,select:disabled').count(), 'next field', await dlg.locator('#numbering-next').count())
await shot(page, R, '05-numbering-inv-locked')
await dlg.getByRole('button', { name: 'ยกเลิก' }).click(); await sleep(500)
// LOT nextSequence ต่ำกว่าเลขที่ใช้แล้ว
await page.locator('tbody tr', { hasText: 'LOT' }).first().getByRole('button', { name: 'แก้ไข' }).click()
dlg = page.getByRole('dialog').last(); await dlg.waitFor(); await sleep(500)
await dlg.locator('#numbering-next').fill('2')
await dlg.locator('#numbering-reason').fill('UAT R15a ทดสอบตั้งเลขต่ำกว่าเลขที่ใช้แล้ว (ต้องถูกปฏิเสธ)')
await dlg.getByRole('button', { name: 'บันทึก' }).click()
log('LOT toasts', await toasts(page, 2500), m.res.splice(0))
log('LOT dialog errors', (await dlg.innerText().catch(() => '')).replace(/\s+/g, ' ').slice(0, 700))
await shot(page, R, '05-numbering-lot-below')
const after = q(`select doc_type,prefix,include_year,digits,reset_yearly,current_seq,updated_at from document_number_series order by doc_type`)
log('unchanged', before === after); if (before !== after) log(after)
log('5xx', serverErrors, 'console', consoleErrors.slice(0, 3))
await browser.close()
