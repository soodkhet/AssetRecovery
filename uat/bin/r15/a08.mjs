// R15a.08 U109 หน้าจอรอบจ่าย (list + detail) + รายงาน F4 — อ่านอย่างเดียว (บริหาร)
import { openAs, shot, log, settle, sleep, R, BASE, yearCE, q } from './_h.mjs'
const { browser, page, serverErrors, consoleErrors } = await openAs('uat.exec')
page.setDefaultTimeout(20000)
await page.goto(`${BASE}/finance?tab=payout`, { timeout: 40000 }); await settle(page); await sleep(1500)
const head = (await page.locator('main thead').first().innerText()).replace(/\s+/g, ' ')
const rows = (await page.locator('main tbody tr').allInnerTexts()).map(s => s.replace(/\s+/g, ' '))
log('list head', head); log('rows', rows)
log('CE', yearCE(await page.locator('main').innerText()))
await shot(page, R, '08-payout-list', { fullPage: true })
for (const i of [0, rows.length - 1]) {
  await page.locator('main tbody tr').nth(i).getByRole('button', { name: 'ดูรายการ' }).click()
  const dlg = page.getByRole('dialog').last(); await dlg.waitFor(); await sleep(1500)
  const t = (await dlg.innerText()).replace(/\s+/g, ' ')
  log('detail', i, t.slice(0, 1800)); log('CE', yearCE(t))
  await shot(page, R, `08-payout-detail-${i}`, { fullPage: true })
  await page.keyboard.press('Escape'); await sleep(500)
}
await page.goto(`${BASE}/reports/compensation`, { timeout: 40000 }); await settle(page); await sleep(2000)
const rt = (await page.locator('main').innerText()).replace(/\s+/g, ' ')
log('F4', rt.slice(0, 2500)); log('CE', yearCE(rt))
await shot(page, R, '08-report-f4', { fullPage: true })
log('5xx', serverErrors, 'console', consoleErrors.slice(0, 3))
await browser.close()
