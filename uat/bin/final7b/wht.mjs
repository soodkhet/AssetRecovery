// บัญชี: ภ.ง.ด. — "ยื่นเพิ่มเติมแล้ว" ก.ย. (U127) และ Mark Filed ต.ค. (เลขอ้างอิงบังคับ)
import { openAs, shot, log, q, collect, trackApi, U, clean } from './_h.mjs'
const [period, btn, ref] = process.argv.slice(2)
const s = await openAs('uat.account'); const { page } = s; const api = trackApi(page)
await page.goto(U + '/accounting?tab=wht'); await page.waitForLoadState('networkidle'); await page.waitForTimeout(1200)
const row = page.locator('tr', { hasText: period }).filter({ has: page.getByRole('button', { name: btn }) }).first()
log('wht', 'row', clean(await row.innerText()))
await row.getByRole('button', { name: btn }).click(); await page.waitForTimeout(900)
const d = page.getByRole('dialog').last(); log('wht', 'dlg', clean(await d.innerText()).slice(0, 900))
const inputs = await d.locator('input, textarea').evaluateAll(es => es.map(e => `${e.type}:${e.id}:${e.placeholder}`)); log('wht', 'inputs', inputs)
const ok = d.getByRole('button', { name: /ยืนยัน|บันทึก/ }).last(); log('wht', 'confirm disabled empty:', await ok.isDisabled())
for (const i of await d.locator('input[type=text], input:not([type])').all()) await i.fill(ref)
for (const ta of await d.locator('textarea').all()) await ta.fill(`ยื่นแบบออนไลน์ อ้างอิง ${ref}`)
await shot(page, `wht-${btn}`.replace(/\s/g, ''), { fullPage: true })
await ok.click(); log('wht', 'act', await collect(page, 4000), api.splice(0).map(x => x.slice(0, 250)))
const t = clean(await page.locator('main').innerText()); log('wht', 'after', t.match(/ต้องยื่น ภ.ง.ด. เพิ่มเติม.{0,80}/)?.[0] ?? 'no supplemental banner', '|', t.match(new RegExp(period + '.{0,160}'))?.[0])
log('wht', 'console', s.consoleErrors, s.serverErrors); await s.browser.close()
