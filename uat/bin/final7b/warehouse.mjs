// Flow 5 — ธุรการ: รับเข้าคลัง FINAL7-001 (IMEI ผิดก่อน) → นัดส่งมอบ (ไฟแนนซ์มารับ) → แนบใบเซ็นรับ → ยืนยันล็อต → รายได้เกิด
import { openAs, shot as shot0, log, q, collect, trackApi } from '../final7b/_h.mjs'

const REF = process.env.REF
const shot = (p, _r, n, o) => shot0(p, n + '-' + process.env.REF, o)
const s = await openAs('uat.admin'); const { page } = s; const api = trackApi(page)
const dt = async () => (await page.locator('[role=dialog]').last().innerText().catch(() => '')).replace(/\s+/g, ' ')
const step = process.argv[2] ?? 'intake'
await page.goto('http://localhost:3000/warehouse'); await page.waitForLoadState('networkidle'); await page.waitForTimeout(800)
if (step === 'intake') {
  const row = page.locator('tr', { hasText: REF }).first()
  log('wh', 'row', (await row.innerText()).replace(/\s+/g, ' '))
  await row.getByRole('button', { name: 'รับเข้าคลัง', exact: true }).click(); await page.waitForTimeout(800)
  const dlg = page.locator('[role=dialog]').last(); const imei = dlg.getByPlaceholder('พิมพ์หรือสแกน IMEI')
  await dlg.getByRole('button', { name: 'ปกติ', exact: true }).click()
  await imei.fill('359847451234562'); await page.waitForTimeout(300)
  await dlg.getByRole('button', { name: /ยืนยันรับ/ }).click(); await page.waitForTimeout(700)
  log('wh', 'IMEI mismatch:', (await dt()).slice(0, 500)); await shot(page, 'final/flow', 'f05-imei-mismatch')
  await imei.fill('3598-4745-1234-561'); await page.waitForTimeout(300)
  log('wh', 'IMEI ok box:', (await dt()).slice(0, 900))
  const cbs = dlg.getByRole('checkbox'); log('wh', 'checkboxes', await cbs.count(), (await cbs.evaluateAll(es => es.map(e => (e.closest('label')?.innerText ?? e.getAttribute('aria-label') ?? '').replace(/\s+/g, ' ')))).join(' | '))
  await dlg.getByRole('button', { name: /ยืนยันรับ/ }).click(); await page.waitForTimeout(700); log('wh', 'confirm w/o tick:', (await dt()).match(/.{0,80}(ติ๊ก|ยืนยันความจุ|ความจุ).{0,120}/)?.[0], api.splice(0).map(x => x.slice(0, 200)))
  for (const c of await cbs.all()) await c.check().catch(() => {})
  await shot(page, 'final/flow', 'f05-intake-ticked', { fullPage: true })
  await dlg.getByRole('button', { name: /ยืนยันรับ/ }).click()
  log('wh', 'intake', await collect(page, 4000), api.splice(0).map(x => x.slice(0, 140)))
  await shot(page, 'final/flow', 'f05-intake-done')
}
if (step === 'lot') {
  await page.getByRole('tab', { name: /^ในคลัง/ }).click(); await page.waitForTimeout(900)
  log('wh', 'custody', (await page.locator('main').innerText()).replace(/\s+/g, ' ').slice(0, 800))
  await page.getByText('บจก. ยูเอที ลิสซิ่ง').last().click(); await page.waitForTimeout(900)
  const cb = page.getByRole('checkbox', { name: `เลือก ${REF}` })
  log('wh', 'cb count', await cb.count()); await cb.check(); await page.waitForTimeout(300)
  await page.getByRole('button', { name: /นัดวันส่งมอบ/ }).click(); await page.waitForTimeout(900)
  const dlg = page.locator('[role=dialog]').last()
  await dlg.getByRole('button', { name: /ไฟแนนซ์มารับที่คลัง/ }).click(); await page.waitForTimeout(300)
  const SCHED = new Date(Date.now() + 7 * 3600e3 + 3600e3).toISOString().slice(0, 16)
  await dlg.locator('input[type=datetime-local]').fill(SCHED)
  await dlg.getByPlaceholder('เช่น คุณวิภา ฝ่ายติดตามทรัพย์').fill('คุณวิภา (ด่าน 7 รอบทวน)')
  await shot(page, 'final/flow', 'f05-lot-form')
  await dlg.getByRole('button', { name: 'บันทึกการนัด' }).click()
  log('wh', 'lot', await collect(page, 4000), api.splice(0).map(x => x.slice(0, 160)))
}
if (step === 'confirm') {
  await page.getByRole('tab', { name: /^รอส่งมอบ/ }).click(); await page.waitForTimeout(1500)
  const card = page.locator('div', { hasText: process.argv[3] }).filter({ has: page.getByRole('button', { name: 'ดูรายการ' }) }).last()
  await card.getByRole('button', { name: 'ดูรายการ' }).click(); await page.waitForTimeout(1000)
  await page.getByRole('button', { name: 'แนบเอกสาร & ยืนยัน' }).click(); await page.waitForTimeout(1000)
  const dlg = page.locator('[role=dialog]').last()
  log('wh', 'confirm dlg', (await dt()).slice(0, 700))
  const btn = dlg.getByRole('button', { name: 'ยืนยันส่งมอบสำเร็จ' })
  log('wh', 'confirm disabled before doc:', await btn.isDisabled())
  const fi = dlg.locator('input[type=file]'); log('wh', 'file inputs', await fi.count())
  await fi.first().setInputFiles('uat/fixtures/files/C1-contract.pdf'); await page.waitForTimeout(3000)
  log('wh', 'after upload', (await dt()).slice(0, 400), 'disabled:', await btn.isDisabled())
  await shot(page, 'final/flow', 'f05-confirm-dlg')
  await btn.click()
  log('wh', 'confirm', await collect(page, 8000), api.splice(0).filter(x => !x.includes('/storage/v1')).map(x => x.slice(0, 160)))
  await page.getByRole('tab', { name: /^ส่งมอบแล้ว/ }).click(); await page.waitForTimeout(1500)
  log('wh', 'delivered tab (U142):', (await page.locator('main').innerText()).replace(/\s+/g, ' ').slice(0, 1500))
  await shot(page, 'final/flow', 'f05-delivered-grouped', { fullPage: true })
}
log('wh', q(`select a.asset_status,a.imei_actual,l.lot_number,l.status,l.type from assets a left join handover_lots l on l.id=a.lot_id where a.case_id=(select id from cases where case_ref='${REF}')`))
log('wh', q(`select r.status,r.gross_satang,r.vat_satang,r.total_satang,r.vat_rate_pct_used,r.vat_mode_snapshot,r.revenue_date from revenues r where r.case_id=(select id from cases where case_ref='${REF}')`).slice(0, 600))
log('wh', 'console', s.consoleErrors, s.serverErrors); await s.browser.close()
